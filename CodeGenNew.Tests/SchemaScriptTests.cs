using System.Data;
using CodeGenNew.Core;

namespace CodeGenNew.Tests;

/// <summary> The create script written from the catalog (SchemaScript, the SP_CreateSchema template), which fills a test container when the project names no ApiTestSchema. </summary>
[TestClass]
public class SchemaScriptTests
{
    private static DatabaseModel Shop(SqlDialect dialect, ForeignKeyDeleteRule rule = ForeignKeyDeleteRule.Cascade)
    {
        var customer = Sample.Table("Customer",
        [
            Sample.Column("CustomerId", SqlDbType.Int, primaryKey: true, identity: true, ordinal: 1),
            Sample.Column("Name", SqlDbType.VarChar, characters: 40, ordinal: 2),
            Sample.Column("Status", SqlDbType.Int, defaultSql: "((1))", ordinal: 3),
            Sample.Column("Note", SqlDbType.VarChar, nullable: true, characters: 100, ordinal: 4)
        ], dialect: dialect, indexes: [new IndexModel("PK_Customer", true, ["CustomerId"]), new IndexModel("UX_Customer_Name", true, ["Name"])]);
        var order = Sample.Table("Order",
        [
            Sample.Column("OrderId", SqlDbType.Int, primaryKey: true, identity: true, ordinal: 1),
            Sample.Column("CustomerId", SqlDbType.Int, ordinal: 2),
            Sample.Column("Total", SqlDbType.Decimal, precision: 10, scale: 2, ordinal: 3)
        ], foreignKeys:
        [
            new ForeignKeyModel { ConstraintName = "FK_Order_Customer", ReferencingColumns = ["CustomerId"], ReferencedSchema = "dbo", ReferencedTable = "Customer", ReferencedColumns = ["CustomerId"], DeleteRule = rule }
        ], dialect: dialect, indexes: [new IndexModel("IX_Order_Customer", false, ["CustomerId"])]);
        return new DatabaseModel { DatabaseName = "Shop", SchemaName = "dbo", Dialect = dialect, Tables = [order, customer] };
    }

    [TestMethod]
    public void SQL_Server_gets_tables_with_identity_defaults_keys_indexes_and_foreign_keys()
    {
        string script = SchemaScript.For(Shop(SqlDialect.SqlServer)).ReplaceLineEndings("\n");

        Expect.Contains(script, "CREATE TABLE [dbo].[Customer] (");
        Expect.Contains(script, "[CustomerId] int IDENTITY(1,1) NOT NULL,");
        Expect.Contains(script, "[Name] varchar(40) NOT NULL,");
        Expect.Contains(script, "[Status] int NOT NULL DEFAULT ((1)),");
        Expect.Contains(script, "[Note] varchar(100) NULL,");
        Expect.Contains(script, "CONSTRAINT [PK_Customer] PRIMARY KEY ([CustomerId])");
        Expect.Contains(script, "CREATE UNIQUE INDEX [UX_Customer_Name] ON [dbo].[Customer] ([Name]);");
        Expect.Contains(script, "CREATE INDEX [IX_Order_Customer] ON [dbo].[Order] ([CustomerId]);");
        Expect.DoesNotContain(script, "CREATE UNIQUE INDEX [PK_Customer]");
        Expect.Contains(script, "ALTER TABLE [dbo].[Order] ADD CONSTRAINT [FK_Order_Customer] FOREIGN KEY ([CustomerId]) REFERENCES [dbo].[Customer] ([CustomerId]) ON DELETE CASCADE;");
    }

    [TestMethod]
    public void The_foreign_keys_come_after_every_table_so_the_order_of_the_tables_does_not_matter()
    {
        string script = SchemaScript.For(Shop(SqlDialect.SqlServer)).ReplaceLineEndings("\n");

        Assert.IsTrue(script.IndexOf("CREATE TABLE [dbo].[Order]", StringComparison.Ordinal) < script.IndexOf("ALTER TABLE [dbo].[Order] ADD CONSTRAINT [FK_Order_Customer]", StringComparison.Ordinal));
        Assert.IsTrue(script.IndexOf("CREATE TABLE [dbo].[Customer]", StringComparison.Ordinal) < script.IndexOf("ALTER TABLE", StringComparison.Ordinal));
    }

    [TestMethod]
    public void PostgreSQL_quotes_with_double_quotes_and_makes_an_identity_column()
    {
        string script = SchemaScript.For(Shop(SqlDialect.PostgreSql)).ReplaceLineEndings("\n");

        Expect.Contains(script, "CREATE TABLE \"dbo\".\"Customer\" (");
        Expect.Contains(script, "\"CustomerId\" int GENERATED BY DEFAULT AS IDENTITY NOT NULL,");
        Expect.Contains(script, "\"Status\" int NOT NULL DEFAULT ((1)),");
        Expect.DoesNotContain(script, "[");
    }

    [TestMethod]
    public void MySQL_names_the_table_alone_and_quotes_a_text_default()
    {
        var database = Shop(SqlDialect.MySql);
        var note = Sample.Column("Kind", SqlDbType.VarChar, characters: 20, defaultSql: "system", ordinal: 5);
        var stamp = Sample.Column("Added", SqlDbType.DateTime, defaultSql: "CURRENT_TIMESTAMP", ordinal: 6);
        var amount = Sample.Column("Fee", SqlDbType.Decimal, precision: 8, scale: 2, defaultSql: "0.00", ordinal: 7);
        var table = Sample.Table("Fee", [Sample.Column("FeeId", SqlDbType.Int, primaryKey: true, identity: true, ordinal: 1), note, stamp, amount], dialect: SqlDialect.MySql);
        database.Tables.Add(table);

        string script = SchemaScript.For(database).ReplaceLineEndings("\n");

        Expect.Contains(script, "CREATE TABLE `Customer` (");
        Expect.Contains(script, "`CustomerId` int AUTO_INCREMENT NOT NULL,");
        Expect.Contains(script, "`Kind` varchar(20) NOT NULL DEFAULT 'system',");
        Expect.Contains(script, "`Added` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,");
        Expect.Contains(script, "`Fee` decimal(8,2) NOT NULL DEFAULT 0.00");
        Expect.Contains(script, "REFERENCES `Customer` (`CustomerId`) ON DELETE CASCADE;");
        Expect.DoesNotContain(script, "dbo");
    }

    [TestMethod]
    [DataRow(ForeignKeyDeleteRule.NoAction, "")]
    [DataRow(ForeignKeyDeleteRule.Cascade, " ON DELETE CASCADE")]
    [DataRow(ForeignKeyDeleteRule.SetNull, " ON DELETE SET NULL")]
    [DataRow(ForeignKeyDeleteRule.Restrict, " ON DELETE RESTRICT")]
    public void A_foreign_key_keeps_its_delete_rule(ForeignKeyDeleteRule rule, string clause)
    {
        string script = SchemaScript.For(Shop(SqlDialect.SqlServer, rule));

        Expect.Contains(script, "REFERENCES [dbo].[Customer] ([CustomerId])" + clause + ";");
    }

    [TestMethod]
    public void Checks_and_partial_indexes_are_written_back_after_the_tables()
    {
        var database = Shop(SqlDialect.SqlServer);
        var old = database.Tables[0];
        database.Tables[0] = Sample.Table("Order", old.Columns, foreignKeys: old.ForeignKeys, indexes: [.. old.Indexes], dialect: SqlDialect.SqlServer,
            partialIndexes: [new PartialIndexModel("UX_Order_Customer", true, ["CustomerId"], ["Total"], "([Total]>(0))")],
            checks: [new CheckConstraintModel("CK_Order_Total", "CHECK ([Total]>=(0))")]);

        string script = SchemaScript.For(database).ReplaceLineEndings("\n");

        Expect.Contains(script, "CREATE UNIQUE INDEX [UX_Order_Customer] ON [dbo].[Order] ([CustomerId]) INCLUDE ([Total]) WHERE ([Total]>(0));");
        Expect.Contains(script, "ALTER TABLE [dbo].[Order] ADD CONSTRAINT [CK_Order_Total] CHECK ([Total]>=(0));");
        Assert.IsTrue(script.IndexOf("CREATE TABLE [dbo].[Customer]", StringComparison.Ordinal) < script.IndexOf("ADD CONSTRAINT [CK_Order_Total]", StringComparison.Ordinal));
    }

    [TestMethod]
    public void SQLite_has_no_container_so_no_script_is_written()
    {
        Assert.IsFalse(SchemaScript.Supports(SqlDialect.Sqlite));
        Assert.AreEqual("", SchemaScript.For(Shop(SqlDialect.Sqlite)));
    }

    [TestMethod]
    public async Task The_template_writes_the_script_as_CreateSchema_sql_and_refuses_SQLite()
    {
        var project = ProjectSettings.FromValues(new Dictionary<string, string> { ["ProjectName"] = "Shop", ["DatabaseProvider"] = "SqlServer" });
        var result = await Repo.Cache.RunAsync(Repo.Template("SP_CreateSchema_v1.tt"), Shop(SqlDialect.SqlServer), project);
        Assert.IsTrue(result.Success, string.Join(" | ", result.Errors));
        Expect.Contains(result.GeneratedText!, "CreateSchema.sql");
        Expect.Contains(result.GeneratedText!, "CREATE TABLE [dbo].[Customer] (");

        var sqlite = await Repo.Cache.RunAsync(Repo.Template("SP_CreateSchema_v1.tt"), Shop(SqlDialect.Sqlite), project);
        Assert.IsFalse(sqlite.Success);
        Expect.Contains(string.Join(" | ", sqlite.Errors), "needs no container");
    }

    private static ProjectSettings Project(params (string Key, string Value)[] values) =>
        ProjectSettings.FromValues(values.Select(v => new KeyValuePair<string, string>(v.Key, v.Value)).Append(new("ProjectName", "Shop")));

    [TestMethod]
    public void The_plan_writes_the_script_only_for_a_container_project_that_names_no_schema_of_its_own()
    {
        CollectionAssert.Contains(Project(("ApiTests", "true"), ("ApiTestContainers", "true"), ("DatabaseProvider", "PostgreSql")).ImpliedPlanTemplates.ToArray(), "SP_CreateSchema");
        CollectionAssert.DoesNotContain(Project(("ApiTests", "true"), ("ApiTestContainers", "true"), ("DatabaseProvider", "PostgreSql"), ("ApiTestSchema", "sql/Create.sql")).ImpliedPlanTemplates.ToArray(), "SP_CreateSchema");
        CollectionAssert.DoesNotContain(Project(("ApiTests", "true"), ("DatabaseProvider", "PostgreSql")).ImpliedPlanTemplates.ToArray(), "SP_CreateSchema");
        CollectionAssert.DoesNotContain(Project(("ApiTests", "true"), ("ApiTestContainers", "true"), ("DatabaseProvider", "Sqlite")).ImpliedPlanTemplates.ToArray(), "SP_CreateSchema");
    }

    [TestMethod]
    public async Task The_test_fixture_fills_the_container_from_the_written_script_and_then_the_routines_unless_the_project_names_its_own()
    {
        var plain = await Repo.Cache.RunAsync(Repo.Template("API_EssentialTests_v1.tt"), Project(("ApiTests", "true"), ("ApiTestContainers", "true"), ("DatabaseProvider", "PostgreSql")));
        var ef = await Repo.Cache.RunAsync(Repo.Template("API_EssentialTests_v1.tt"), Project(("ApiTests", "true"), ("ApiTestContainers", "true"), ("DatabaseProvider", "PostgreSql"), ("AccessMode", "Ef")));
        var own = await Repo.Cache.RunAsync(Repo.Template("API_EssentialTests_v1.tt"), Project(("ApiTests", "true"), ("ApiTestContainers", "true"), ("DatabaseProvider", "PostgreSql"), ("ApiTestSchema", "db/create.sql")));
        Assert.IsTrue(plain.Success && ef.Success && own.Success, string.Join(" | ", plain.Errors.Concat(ef.Errors).Concat(own.Errors)));

        Expect.Contains(plain.GeneratedText!, "SchemaScripts = [\"../sql/CreateSchema.sql\", \"../sql\"];");
        Expect.Contains(ef.GeneratedText!, "SchemaScripts = [\"../sql/CreateSchema.sql\"];");
        Expect.Contains(own.GeneratedText!, "SchemaScripts = [\"db/create.sql\"];");
        Expect.Contains(plain.GeneratedText!, ".Where(seen.Add)");
    }
}

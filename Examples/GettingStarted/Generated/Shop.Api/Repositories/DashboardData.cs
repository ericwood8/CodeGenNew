namespace Shop.Api.Repositories;

using System.Collections.Concurrent;
using Microsoft.EntityFrameworkCore;

/// <summary> One value of a widget: a label and a number (a count, a sum, one month of a trend). </summary>
public class DashboardPoint
{
    public string? Label { get; set; }
    public double? Value { get; set; }
}

/// <summary> One line of a recent-rows widget: what the row is called and its date. </summary>
public class DashboardRow
{
    public string? Label { get; set; }
    public string? Detail { get; set; }
}

/// <summary> A widget with its data. Kind is count, childCount, money, topBy, breakdown, trend, ratio, status or recent; a recent widget fills Rows, every other one Points. </summary>
public partial class DashboardWidgetData
{
    public string Id { get; set; } = "";
    public string Kind { get; set; } = "";
    public string Title { get; set; } = "";
    public string Table { get; set; } = "";
    /// <summary> The route of the table's screen (empty when it has none), where a click on the widget goes. </summary>
    public string Route { get; set; } = "";
    /// <summary> True when the numbers are amounts of money, so a page shows them as currency. </summary>
    public bool IsMoney { get; set; }
    public List<DashboardPoint> Points { get; set; } = [];
    public List<DashboardRow> Rows { get; set; } = [];
}

public class DashboardResult
{
    public List<DashboardWidgetData> Widgets { get; set; } = [];
}

/// <summary> Generated by CS_Dashboard from the schema's own facts (money columns, foreign keys, lookup and choice columns, dates). Change the choice with the project's Dashboard settings and regenerate. </summary>
public static class DashboardData
{
    private sealed record Definition(string Id, string Kind, string Title, string Table, string Route, bool IsMoney, bool IsRows, bool OnDashboard, bool OnStrip, string Sql);

    private static readonly Definition[] Definitions =
    [
        new("customer-child-count", "childCount", "Customers and Sales Orders", "Customer", "customer", false, false, true, false,
            "SELECT 'Customers' AS \"Label\", CAST(COUNT(*) AS REAL) AS \"Value\" FROM \"customer\" UNION ALL SELECT 'Sales Orders' AS \"Label\", CAST(COUNT(*) AS REAL) AS \"Value\" FROM \"sales_order\""),
        new("customer-breakdown-status", "breakdown", "Customers by Status", "Customer", "customer", false, false, true, false,
            "SELECT COALESCE(\"status\", '(none)') AS \"Label\", CAST(COUNT(*) AS REAL) AS \"Value\" FROM \"customer\" GROUP BY \"status\" ORDER BY COUNT(*) DESC"),
        new("sales-order-breakdown-product-id", "breakdown", "Sales Orders by Product", "SalesOrder", "sales-order", false, false, true, false,
            "SELECT COALESCE(p.\"name\", '(none)') AS \"Label\", CAST(COUNT(*) AS REAL) AS \"Value\" FROM \"sales_order\" t INNER JOIN \"product\" p ON p.\"product_id\" = t.\"product_id\" GROUP BY p.\"name\" ORDER BY COUNT(*) DESC"),
        new("sales-order-trend-order-date", "trend", "Sales Orders per Month", "SalesOrder", "sales-order", false, false, true, false,
            "SELECT date(b) AS \"Label\", CAST(COUNT(*) AS REAL) AS \"Value\" FROM (SELECT strftime('%Y-%m-01', \"order_date\") AS b FROM \"sales_order\" WHERE \"order_date\" >= datetime(strftime('%Y-%m-01', (SELECT MAX(\"order_date\") FROM \"sales_order\")), '-11 months')) x GROUP BY b ORDER BY b"),
        new("customer-recent", "recent", "Latest Customers", "Customer", "customer", false, true, true, false,
            "SELECT CAST(\"name\" AS TEXT) AS \"Label\", CAST(\"customer_id\" AS TEXT) AS \"Detail\" FROM \"customer\" ORDER BY \"customer_id\" DESC LIMIT 10 OFFSET 0"),
    ];

    private static readonly TimeSpan CacheFor = TimeSpan.FromMinutes(1);
    private static readonly ConcurrentDictionary<string, (DateTime Expires, DashboardResult Result)> Cache = new();

    /// <summary> The tables whose screens show a strip of cards (the DashboardStrip project setting). </summary>
    public static readonly string[] StripTables = [];

    /// <summary> The dashboard page's widgets, or with <paramref name="table"/> the cards of that table's strip (empty for a table that has none). <paramref name="useCache"/> keeps the answer for a minute. </summary>
    public static async Task<DashboardResult> LoadAsync(ShopContext context, string? table = null, bool useCache = false, CancellationToken cancellationToken = default)
    {
        string key = table is null ? "" : "table:" + table;
        if (useCache && Cache.TryGetValue(key, out var cached) && cached.Expires > DateTime.UtcNow)
            return cached.Result;

        var chosen = table is null
            ? Definitions.Where(d => d.OnDashboard)
            : Definitions.Where(d => d.OnStrip && string.Equals(d.Table, table, StringComparison.OrdinalIgnoreCase));
        var result = new DashboardResult();
        foreach (var d in chosen)
        {
            var data = new DashboardWidgetData { Id = d.Id, Kind = d.Kind, Title = d.Title, Table = d.Table, Route = d.Route, IsMoney = d.IsMoney };
            if (d.IsRows)
                data.Rows = await context.Database.SqlQueryRaw<DashboardRow>(d.Sql).ToListAsync(cancellationToken);
            else
                data.Points = await context.Database.SqlQueryRaw<DashboardPoint>(d.Sql).ToListAsync(cancellationToken);
            result.Widgets.Add(data);
        }

        if (useCache)
            Cache[key] = (DateTime.UtcNow + CacheFor, result);
        return result;
    }
}

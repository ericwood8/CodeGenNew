using System.Text.Json;
using System.Text.Json.Serialization;

var builder = WebApplication.CreateBuilder(args);

// The provider (UseSqlite) is chosen in the generated ShopContext.
builder.Services.AddGeneratedDbContext(builder.Configuration);

// Every error answers as problem details (Problems.cs): a refused database write says why, an unexpected failure says nothing of the server.
builder.Services.AddApiProblems();

// Entities point at each other (an invoice at its customer, a customer at its invoices); do not follow the loop when writing JSON.
builder.Services.ConfigureHttpJsonOptions(options =>
{
    options.SerializerOptions.ReferenceHandler = ReferenceHandler.IgnoreCycles;
    options.SerializerOptions.PropertyNamingPolicy = JsonNamingPolicy.CamelCase;
});

// The React dev server proxies /api here (see frontend/vite.config.ts), so CORS only matters if the front end is served elsewhere.
builder.Services.AddCors(options => options.AddDefaultPolicy(policy =>
    policy.WithOrigins("http://localhost:5173").AllowAnyHeader().AllowAnyMethod()));

var app = builder.Build();
app.UseApiProblems();
app.UseCors();

// ApiRegistration.cs (generated by API_Registration) has one line per table. The Search classes need the <Table>_Search / <Table>_SearchCount routines in the database (the sql folder).
app.RegisterGeneratedApis();

app.Run();

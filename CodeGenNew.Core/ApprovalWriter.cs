using System.Text;

namespace CodeGenNew.Core;

/// <summary> The C# of the row approvals (<c>RowApprovals</c>): the shared types once, then one static class per table with the request, approve, reject and withdraw routes, the list of requests waiting for
/// the signed-in approver and the history of a row. The text is a template with <c>§</c> tokens so the code reads as code. </summary>
public static class ApprovalWriter
{
    public const string RequesterUnknownType = ProblemTypes.Prefix + "approval-requester-unknown";
    public const string NotApproverType = ProblemTypes.Prefix + "approval-not-approver";
    public const string FourEyesType = ProblemTypes.Prefix + "approval-four-eyes";
    public const string WrongStateType = ProblemTypes.Prefix + "approval-wrong-state";
    public const string RefusedType = ProblemTypes.Prefix + "approval-refused";

    /// <summary> The whole file for the plan, ending in a line feed. </summary>
    public static string File(ApprovalPlan plan, string contextType, string[] usings)
    {
        var user = plan.User!;
        string adminTest = user.Admin is { } admin ? $"u.{admin.CSharpName()} == true" : "false";
        var o = new StringBuilder();
        foreach (string u in usings)
            o.Append($"using {u};\n");
        o.Append("using System.Security.Claims;\nusing Microsoft.EntityFrameworkCore;\n\n");
        o.Append(Fill(Shared, ("§CTX", contextType), ("§U", user.Table.TableName), ("§UN", user.UserName.CSharpName()),
            ("§UF", user.Role!.CSharpName()), ("§UA", adminTest), ("§PENDING", ApprovalStatus.Pending.ToString()), ("§APPROVED", ApprovalStatus.Approved.ToString()),
            ("§REJECTED", ApprovalStatus.Rejected.ToString()), ("§WITHDRAWN", ApprovalStatus.Withdrawn.ToString()),
            ("§T_UNKNOWN", RequesterUnknownType), ("§T_NOTAPPROVER", NotApproverType), ("§T_FOUREYES", FourEyesType), ("§T_STATE", WrongStateType), ("§T_REFUSED", RefusedType)));
        foreach (var table in plan.Tables)
            o.Append(PerTable(table, contextType));
        o.Append("/// <summary> Maps the approval routes of every table named in RowApprovals. Generated by API_Approvals. </summary>\npublic static class ApprovalsApi\n{\n    public static void Register(WebApplication app)\n    {\n");
        foreach (var table in plan.Tables)
            o.Append($"        {table.Table.TableName}Approvals.Map(app);\n");
        o.Append("    }\n}\n");
        return o.ToString();
    }

    private static string Now(ColumnModel column) => column.SqlType == System.Data.SqlDbType.DateTimeOffset ? "DateTimeOffset.Now" : "DateTime.Now";

    private static string PerTable(ApprovalTable t, string contextType)
    {
        string keyType = t.Key.CSharpBase();
        return Fill(Table,
            ("§CTX", contextType), ("§T", t.Table.TableName), ("§A", t.Side.TableName), ("§R", ApiRequests.Route(t.Table)), ("§KT", keyType), ("§K", t.Key.CSharpName()),
            ("§L", t.Link.CSharpName()), ("§ST", t.Status.CSharpName()), ("§RV", t.Revision.CSharpName()), ("§ID", t.SideKey.CSharpName()), ("§RS", t.Reason.CSharpName()),
            ("§RB", t.RequestedBy.CSharpName()), ("§RO", t.RequestedOn.CSharpName()), ("§DB", t.DecidedBy.CSharpName()), ("§DO", t.DecidedOn.CSharpName()), ("§DN", t.DecisionNote.CSharpName()),
            ("§NOWRO", Now(t.RequestedOn)), ("§NOWDO", Now(t.DecidedOn)), ("§TYPERO", t.RequestedOn.CSharpBase()), ("§TYPEDO", t.DecidedOn.CSharpBase() + "?"),
            ("§PENDING", ApprovalStatus.Pending.ToString()), ("§APPROVED", ApprovalStatus.Approved.ToString()), ("§REJECTED", ApprovalStatus.Rejected.ToString()), ("§WITHDRAWN", ApprovalStatus.Withdrawn.ToString()));
    }

    private static string Fill(string text, params (string Token, string Value)[] values)
    {
        // longest token first, so §ID is not read as the start of another
        foreach (var (token, value) in values.OrderByDescending(v => v.Token.Length))
            text = text.Replace(token, value);
        return text;
    }

    private const string Shared = """
/// <summary> What a caller sends with a request or a decision. </summary>
public sealed record ApprovalNote(string? Reason, string? Note);

/// <summary> One request cycle of a row, as the routes answer it. </summary>
public sealed record ApprovalView(int Id, object RowId, int Revision, string Status, string? Reason, string RequestedBy, object RequestedOn, string? DecidedBy, object? DecidedOn, string? DecisionNote);

/// <summary> What happened, handed to the project's hooks. <c>Context</c> is the same context the route saves with, so a change made in <c>OnDecided</c> is saved in the decision's transaction. </summary>
public sealed record ApprovalEvent(§CTX Context, string Table, object RowId, string Action, string Person, int Revision);

/// <summary> The two places a project adds its own rules. <c>Validate</c> runs before a request, an approval, a rejection or a withdrawal and must have no side effects: a sentence refuses it (409).
/// <c>OnDecided</c> runs after an approval or rejection is written and before it is committed. </summary>
public static class ApprovalHooks
{
    public static Func<ApprovalEvent, Task<string?>>? Validate { get; set; }
    public static Func<ApprovalEvent, Task>? OnDecided { get; set; }
}

/// <summary> The signed-in person as the user table knows them: <c>MayDecide</c> is an administrator or a person whose role flag is set. </summary>
public sealed record ApprovalPerson(string Name, bool MayDecide);

public static class ApprovalPeople
{
    public static async Task<ApprovalPerson?> FindAsync(§CTX context, ClaimsPrincipal caller)
    {
        string? name = caller.FindFirstValue(AuthNames.NameClaim);
        if (string.IsNullOrEmpty(name))
            return null;
        var row = await context.Set<§U>().AsNoTracking().Where(u => u.§UN == name).Select(u => new { Name = u.§UN, Flag = u.§UF == true, Admin = §UA }).FirstOrDefaultAsync();
        return row is null ? null : new ApprovalPerson(row.Name!, row.Flag || row.Admin || caller.IsInRole(AuthNames.AdminRole));
    }
}

public static class ApprovalProblems
{
    public static IResult RequesterUnknown() => Results.Problem(statusCode: 403, type: "§T_UNKNOWN", title: "Not allowed", detail: "You are not a person of the user table, so you cannot request or decide.");
    public static IResult NotApprover() => Results.Problem(statusCode: 403, type: "§T_NOTAPPROVER", title: "Not allowed", detail: "Only an administrator or a person with the approver role may decide.");
    public static IResult NotRequester() => Results.Problem(statusCode: 403, type: "§T_NOTAPPROVER", title: "Not allowed", detail: "Only the person who made the request can withdraw it.");
    public static IResult FourEyes() => Results.Problem(statusCode: 403, type: "§T_FOUREYES", title: "Not allowed", detail: "A request is decided by someone other than the person who made it.");
    public static IResult WrongState(string detail) => Results.Problem(statusCode: 409, type: "§T_STATE", title: "Wrong state", detail: detail);
    public static IResult Refused(string detail) => Results.Problem(statusCode: 409, type: "§T_REFUSED", title: "Refused", detail: detail);

    public static string Name(int status) => status switch { §PENDING => "Pending", §APPROVED => "Approved", §REJECTED => "Rejected", §WITHDRAWN => "Withdrawn", _ => "Unknown" };
}

""";

    private const string Table = """
/// <summary> The approval routes of §T: one request cycle per row of §A. Generated by API_Approvals. </summary>
public static class §TApprovals
{
    private static ApprovalView View(§A a) => new(a.§ID, a.§L, a.§RV, ApprovalProblems.Name(a.§ST), a.§RS, a.§RB, a.§RO, a.§DB, a.§DO, a.§DN);

    private static Task<§A?> LatestAsync(§CTX context, §KT id) =>
        context.Set<§A>().AsNoTracking().Where(a => a.§L == id).OrderByDescending(a => a.§RV).FirstOrDefaultAsync();

    private static async Task<IResult?> RefuseAsync(§CTX context, §KT id, string action, string person, int revision) =>
        ApprovalHooks.Validate is { } validate && await validate(new ApprovalEvent(context, "§T", id, action, person, revision)) is { } refusal ? ApprovalProblems.Refused(refusal) : null;

    public static async Task<IResult> RequestAsync(§CTX context, ClaimsPrincipal caller, §KT id, ApprovalNote? body)
    {
        var person = await ApprovalPeople.FindAsync(context, caller);
        if (person is null)
            return ApprovalProblems.RequesterUnknown();
        if (!await context.Set<§T>().AsNoTracking().AnyAsync(r => r.§K == id))
            return Results.NotFound();
        var latest = await LatestAsync(context, id);
        if (latest is not null && latest.§ST == §PENDING)
            return ApprovalProblems.WrongState("A request for this row is already waiting for a decision.");
        int revision = (latest?.§RV ?? 0) + 1;
        if (await RefuseAsync(context, id, "request", person.Name, revision) is { } refused)
            return refused;
        var cycle = new §A { §L = id, §ST = §PENDING, §RS = body?.Reason, §RB = person.Name, §RO = §NOWRO, §RV = revision };
        context.Add(cycle);
        await context.SaveChangesAsync();
        return Results.Ok(View(cycle));
    }

    public static async Task<IResult> DecideAsync(§CTX context, ClaimsPrincipal caller, §KT id, ApprovalNote? body, int status, string action)
    {
        var person = await ApprovalPeople.FindAsync(context, caller);
        if (person is null)
            return ApprovalProblems.RequesterUnknown();
        if (!person.MayDecide)
            return ApprovalProblems.NotApprover();
        var latest = await LatestAsync(context, id);
        if (latest is null || latest.§ST != §PENDING)
            return ApprovalProblems.WrongState("No request for this row is waiting for a decision.");
        if (string.Equals(latest.§RB, person.Name, StringComparison.OrdinalIgnoreCase))
            return ApprovalProblems.FourEyes();
        if (await RefuseAsync(context, id, action, person.Name, latest.§RV) is { } refused)
            return refused;
        await using var transaction = await context.Database.BeginTransactionAsync();
        string? note = body?.Note;
        var decidedOn = §NOWDO;
        int changed = await context.Set<§A>().Where(a => a.§ID == latest.§ID && a.§ST == §PENDING)
            .ExecuteUpdateAsync(s => s.SetProperty(a => a.§ST, status).SetProperty(a => a.§DB, person.Name).SetProperty(a => a.§DO, decidedOn).SetProperty(a => a.§DN, note));
        if (changed == 0)
            return ApprovalProblems.WrongState("The request was decided by someone else a moment ago.");
        if (ApprovalHooks.OnDecided is { } decided)
            await decided(new ApprovalEvent(context, "§T", id, action, person.Name, latest.§RV));
        await context.SaveChangesAsync();
        await transaction.CommitAsync();
        return Results.Ok(View((await LatestAsync(context, id))!));
    }

    public static async Task<IResult> WithdrawAsync(§CTX context, ClaimsPrincipal caller, §KT id)
    {
        var person = await ApprovalPeople.FindAsync(context, caller);
        if (person is null)
            return ApprovalProblems.RequesterUnknown();
        var latest = await LatestAsync(context, id);
        if (latest is null || latest.§ST != §PENDING)
            return ApprovalProblems.WrongState("No request for this row is waiting for a decision.");
        if (!string.Equals(latest.§RB, person.Name, StringComparison.OrdinalIgnoreCase))
            return ApprovalProblems.NotRequester();
        if (await RefuseAsync(context, id, "withdraw", person.Name, latest.§RV) is { } refused)
            return refused;
        var decidedOn = §NOWDO;
        int changed = await context.Set<§A>().Where(a => a.§ID == latest.§ID && a.§ST == §PENDING)
            .ExecuteUpdateAsync(s => s.SetProperty(a => a.§ST, §WITHDRAWN).SetProperty(a => a.§DB, person.Name).SetProperty(a => a.§DO, decidedOn));
        if (changed == 0)
            return ApprovalProblems.WrongState("The request was decided a moment ago.");
        return Results.Ok(View((await LatestAsync(context, id))!));
    }

    public static async Task<IResult> ToApproveAsync(§CTX context, ClaimsPrincipal caller)
    {
        var person = await ApprovalPeople.FindAsync(context, caller);
        if (person is null)
            return ApprovalProblems.RequesterUnknown();
        if (!person.MayDecide)
            return ApprovalProblems.NotApprover();
        var waiting = await context.Set<§A>().AsNoTracking().Where(a => a.§ST == §PENDING && a.§RB != person.Name).OrderBy(a => a.§RO).ToListAsync();
        return Results.Ok(waiting.Select(View));
    }

    public static async Task<IResult> HistoryAsync(§CTX context, §KT id)
    {
        var cycles = await context.Set<§A>().AsNoTracking().Where(a => a.§L == id).OrderByDescending(a => a.§RV).ToListAsync();
        return Results.Ok(cycles.Select(View));
    }

    public static void Map(WebApplication app)
    {
        app.MapGet("§R/toapprove", ToApproveAsync).RequireAuthorization();
        app.MapGet("§R/{id}/approvals", HistoryAsync).RequireAuthorization();
        app.MapPost("§R/{id}/request", RequestAsync).RequireAuthorization();
        app.MapPost("§R/{id}/approve", (§CTX context, ClaimsPrincipal caller, §KT id, ApprovalNote? body) => DecideAsync(context, caller, id, body, §APPROVED, "approve")).RequireAuthorization();
        app.MapPost("§R/{id}/reject", (§CTX context, ClaimsPrincipal caller, §KT id, ApprovalNote? body) => DecideAsync(context, caller, id, body, §REJECTED, "reject")).RequireAuthorization();
        app.MapPost("§R/{id}/withdraw", WithdrawAsync).RequireAuthorization();
    }
}

""";
}

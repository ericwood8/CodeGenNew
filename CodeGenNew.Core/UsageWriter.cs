    private const string RollupBlock = """
    /// <summary> What a roll-up did: the events it totalled and removed, and the monthly rows it wrote or added to. </summary>
    public sealed record RolledUp(int Events, int Months);

    /// <summary> Events older than this many days are rolled up (UsageRollupDays). </summary>
    public const int RollupDays = §DAYS;

    /// <summary> The first day of the month before which events are rolled up: the month that contains today minus <see cref="RollupDays"/>. It is never later than the start of this month, so a month the plan limit still reads is never rolled. </summary>
    public static DateTime RollupBefore(DateTime? now = null) => MonthStart((now ?? DateTime.UtcNow).AddDays(-RollupDays));

    /// <summary> Adds the events before <paramref name="before"/> (default <see cref="RollupBefore"/>, never later than this month) into the monthly totals of §M and removes them, a thousand at a time, each batch in one transaction: an event is removed only when it was counted. The owner's scheduler calls this. </summary>
    public static async Task<RolledUp> RollUpAsync(§CTX context, DateTime? before = null, CancellationToken cancellationToken = default)
    {
        var cutoff = before is { } asked && asked < MonthStart() ? asked : RollupBefore();
        int events = 0, months = 0;
        while (true)
        {
            var batch = await context.Set<§T>().IgnoreQueryFilters().AsNoTracking().Where(x => x.§OCC < cutoff).OrderBy(x => x.§K).Take(1000)
                .Select(x => new { Id = x.§K, Tenant = x.§TENANT, Kind = x.§KIND, At = x.§OCC, Units = §UNITSEXPR }).ToListAsync(cancellationToken);
            if (batch.Count == 0)
                break;
            await using var transaction = await context.Database.BeginTransactionAsync(cancellationToken);
            foreach (var group in batch.GroupBy(x => new { x.Tenant, x.Kind, x.At.Year, x.At.Month }))
            {
                int year = group.Key.Year, month = group.Key.Month;
                var first = §MONTHVALUE;
                var units = group.Sum(x => x.Units);
                var row = await context.Set<§M>().IgnoreQueryFilters().FirstOrDefaultAsync(r => r.§MT == group.Key.Tenant && r.§MK == group.Key.Kind && r.§MM == first, cancellationToken);
                if (row is null)
                    context.Set<§M>().Add(new §M { §MT = group.Key.Tenant, §MK = group.Key.Kind, §MM = first, §MQ = checked((§MQTYPE)units) });
                else
                    row.§MQ = checked((§MQTYPE)(row.§MQ + units));
                months++;
            }
            var ids = batch.Select(x => x.Id).ToList();
            await context.SaveChangesAsync(cancellationToken);
            await context.Set<§T>().IgnoreQueryFilters().Where(x => ids.Contains(x.§K)).ExecuteDeleteAsync(cancellationToken);
            await transaction.CommitAsync(cancellationToken);
            events += batch.Count;
            context.ChangeTracker.Clear();
        }
        return new RolledUp(events, months);
    }

""";


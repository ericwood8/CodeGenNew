    /// <summary> The lock a refusing <c>RecordAsync</c> holds from the check against the plan to the write, so two requests at the same moment cannot both read the month before either writes: a transaction that locks the
    /// tenant's row (SQL Server, PostgreSQL, MySQL; a caller's own transaction is joined, and its commit releases the lock), or one lock of the process for SQLite. </summary>
    private static string GateClass(DatabaseModel database, UsageShape t, string contextType)
    {
        var di = DialectInfo.For(database.Dialect);
        var tenantTable = database.Tables.First(x => x.TableName.EqualsIgnoreCase(t.TenantTable));
        string table = di.QuoteTable(tenantTable.SchemaName, tenantTable.DbTableName), key = di.Quote(TenantPlan.KeyOf(tenantTable)!.DbName);
        string sql = database.Dialect switch
        {
            SqlDialect.SqlServer => $"SELECT 1 FROM {table} WITH (UPDLOCK, ROWLOCK) WHERE {key} = {{0}}",
            _ => $"SELECT 1 FROM {table} WHERE {key} = {{0}} FOR UPDATE"
        };
        string enter = database.Dialect == SqlDialect.Sqlite
            ? "        await Local.WaitAsync(cancellationToken);\n        return new UsageGate(null, true);\n"
            : "        if (context.Database.CurrentTransaction is not null)\n        {\n            await context.Database.ExecuteSqlRawAsync(\"" + sql.Replace("\"", "\\\"") + "\", [tenant], cancellationToken);\n            return new UsageGate(null, false);\n        }\n"

using System.Text;

namespace CodeGenNew.Core;

/// <summary> The asset code of the WinUI3 app, which reads the database itself and so never meets the API's routes: <c>Assets.cs</c> holds the store, the key rules and the limits (the text the API's file starts with) and,
/// for each table in <c>AssetTables</c>, a static class <c>&lt;Table&gt;Assets</c> with the same rules: the dialogs call <c>PrepareAsync</c> before a save (a new row holds an unattached key, an edit keeps the stored
/// key, type and size), the list page calls <c>UploadAsync</c> and <c>ExportAsync</c>, and a delete reads the key first and removes the file once the row is gone. </summary>
public static class AssetDesktopCode
{
    /// <summary> The lines of <c>SaveAsync</c> that run <c>PrepareAsync</c> of an asset table on the row before it is saved (eight spaces in); empty for any other table. </summary>
    public static string CheckLines(ProjectSettings project, TableModel table, string context)
    {
        if (TableShapes.For(table, project).Asset is null)
            return "";
        var o = new StringBuilder();
        o.Append($"        if (await {table.TableName}Assets.PrepareAsync({context}, entity, _editing is null) is {{ }} assetRefusal)\n");
        o.Append("        {\n");
        o.Append("            ErrorMessage = assetRefusal;\n");
        o.Append("            return false;\n");
        o.Append("        }\n\n");
        return o.ToString();
    }

    public static string File(DatabaseModel database, ProjectSettings project, string repositoryNamespace, string contextType, string[] usings)
    {
        var o = new StringBuilder();
        o.Append($"namespace {repositoryNamespace};\n\n");
        foreach (string u in usings)
            o.Append($"using {u};\n");
        o.Append("using Microsoft.EntityFrameworkCore;\nusing Microsoft.Extensions.DependencyInjection;\n\n");
        o.Append(RowShapeWriter.AssetCommonCode(project));
        foreach (var table in database.Tables.OrderBy(t => t.TableName, StringComparer.OrdinalIgnoreCase))
        {
            if (TableShapes.For(table, project).Asset is not { } asset)
                continue;
            int Room(ColumnModel c) => c.CharacterLength > 0 ? c.CharacterLength : int.MaxValue;
            string name = table.TableName;
            o.Append(TemplateText.FillAll(PerTable,
                ("§TABLE", name), ("§CTX", contextType), ("§T", name), ("§KT", asset.Key.CSharpBase()), ("§K", asset.Key.CSharpName()),
                ("§STORAGEKEY", asset.StorageKey.CSharpName()), ("§FILENAME", asset.FileName.CSharpName()), ("§MIMECOL", asset.MimeType.CSharpName()), ("§SIZECOL", asset.Size.CSharpName()), ("§SIZETYPE", asset.Size.CSharpBase()),
                ("§NAMEMAX", Room(asset.FileName).ToString()), ("§MIMEMAX", Room(asset.MimeType).ToString()), ("§INSERTSQL", ApiSampleValues.Json(RowShapeWriter.AssetInsertSql(table, asset, database.Dialect))),
                ("§NOFILE", ApiSampleValues.Json(AssetWords.NoFile)), ("§TOOLARGE", ApiSampleValues.Json(AssetWords.TooLarge(project.AssetMaxBytes))),
                ("§NOTALLOWED", ApiSampleValues.Json(AssetWords.TypeNotAllowed(AssetPlan.AllowedTypes(project)))), ("§MISSING", ApiSampleValues.Json(AssetWords.FileMissing))));
        }
        return o.ToString();
    }

    private const string PerTable = """"

/// <summary> The asset rules of §TABLE (AssetTables) for the desktop app: the same checks the API writes. Generated by WinUI3_Assets. </summary>
public static class §TABLEAssets
{
    /// <summary> Run before a save: a new row holds an unattached key (no file is behind it) and an edit keeps the stored key, type and size, which only an upload sets. Returns a sentence when the save is refused. </summary>
    public static async Task<string?> PrepareAsync(§CTX context, §T entity, bool isNew)
    {
        if (isNew)
        {
            entity.§STORAGEKEY = AssetKeys.Unattached();
            return null;
        }
        var stored = await context.Set<§T>().AsNoTracking().Where(x => x.§K == entity.§K).Select(x => new { x.§STORAGEKEY, x.§MIMECOL, x.§SIZECOL }).FirstOrDefaultAsync();
        if (stored is not null)
        {
            entity.§STORAGEKEY = stored.§STORAGEKEY;
            entity.§MIMECOL = stored.§MIMECOL;
            entity.§SIZECOL = stored.§SIZECOL;
        }
        return null;
    }

    /// <summary> Copies the file at <paramref name="path"/> into the store under a key made here and adds its row. Returns a sentence when the file is refused or cannot be stored, else null. </summary>
    public static async Task<string?> UploadAsync(§CTX context, string path, string? contentType)
    {
        var info = new System.IO.FileInfo(path);
        if (!info.Exists || info.Length == 0)
            return §NOFILE;
        if (info.Length > AssetLimits.MaxBytes)
            return §TOOLARGE;
        string mime = AssetKeys.CleanType(contentType);
        if (!AssetLimits.Accepts(mime))
            return §NOTALLOWED;
        string key = AssetKeys.Make(info.Name);
        try
        {
            await using (var content = System.IO.File.OpenRead(path))
                await AssetStores.Current.SaveAsync(key, content, CancellationToken.None);
            await context.Database.SqlQueryRaw<§KT>(§INSERTSQL, key, AssetKeys.CleanName(info.Name, §NAMEMAX), AssetKeys.Cut(mime, §MIMEMAX), (§SIZETYPE)info.Length).ToListAsync();
            return null;
        }
        catch (Exception ex)
        {
            await AssetStores.Current.DeleteAsync(key, CancellationToken.None);
            return ex.Message;
        }
    }

    /// <summary> Writes the file of a row to <paramref name="destination"/>. Returns a sentence when the row has no file, else null. </summary>
    public static async Task<string?> ExportAsync(§CTX context, §KT id, string destination)
    {
        string? key = await context.Set<§T>().AsNoTracking().Where(x => x.§K == id).Select(x => x.§STORAGEKEY).FirstOrDefaultAsync();
        if (key is null)
            return "This row no longer exists.";
        string? problem;
        await using (var target = System.IO.File.Create(destination))
            problem = await CopyFileAsync(key, target);
        if (problem is not null)
            System.IO.File.Delete(destination);
        return problem;
    }

    /// <summary> Copies the stored file under <paramref name="key"/> to <paramref name="target"/>. Returns a sentence when no file is behind the key, else null. </summary>
    public static async Task<string?> CopyFileAsync(string key, System.IO.Stream target)
    {
        await using var stored = key.StartsWith(AssetKeys.UnattachedPrefix, StringComparison.Ordinal) || !AssetKeys.IsSafe(key) ? null : await AssetStores.Current.OpenAsync(key, CancellationToken.None);
        if (stored is null)
            return §MISSING;
        await stored.CopyToAsync(target);
        return null;
    }

    /// <summary> Before a delete: remembers the storage key of the row, so the file can be removed once the row is gone. </summary>
    public static async Task RememberFileAsync(§CTX context, §KT id)
    {
        string? key = await context.Set<§T>().AsNoTracking().Where(x => x.§K == id).Select(x => x.§STORAGEKEY).FirstOrDefaultAsync();
        if (key is not null && !key.StartsWith(AssetKeys.UnattachedPrefix, StringComparison.Ordinal))
            AssetPending.Remember(context, key);
    }

    /// <summary> After a delete that worked: removes the file. A delete the database refused keeps it. </summary>
    public static async Task AfterDeleteAsync(§CTX context)
    {
        if (AssetPending.Take(context) is { } key)
            await AssetStores.Current.DeleteAsync(key, CancellationToken.None);
    }
}
"""";
}

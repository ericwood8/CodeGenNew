namespace CodeGenNew.Core;

/// <summary> The C# source of the <c>MySqlSpatial</c> class the generated EF Core context carries when a MySQL column is a spatial type: a value converter between the column's text (well-known text, longitude
/// first as the binary form stores it) and the binary form MySQL keeps (a 4-byte spatial reference system id and the geometry as well-known binary). </summary>
public static class MySqlSpatialSource
{
    public const string Code = """
/// <summary> Value converters for the MySQL spatial columns, which the entities hold as well-known text: POINT(1 2), POLYGON((0 0,0 1,1 1,0 0)). MySQL keeps such a column as
/// four bytes of spatial reference system id and the geometry as well-known binary; this turns one into the other. Generated by CS_DbContext; regenerate it rather than edit it. </summary>
internal static class MySqlSpatial
{
    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    /// <summary> The entity holds text, so a change is a change of the text. </summary>
    public static readonly Microsoft.EntityFrameworkCore.ChangeTracking.ValueComparer<string> Comparer = new((a, b) => a == b, v => v.GetHashCode(), v => v);

    public static ValueConverter<string, byte[]> Converter(int srid) => new(v => ToBinary(v, srid), v => ToText(v));

    private sealed class Shape
    {
        public int Kind;                                    // 1 point, 2 line string, 3 polygon, 4 multipoint, 5 multi line string, 6 multipolygon, 7 collection
        public List<double[]> Points = [];                  // a point, or the points of a line string
        public List<Shape> Parts = [];                      // the rings of a polygon, the members of a multi shape or a collection
    }

    // ----- text to binary -----

    private static byte[] ToBinary(string text, int srid)
    {
        int position = 0;
        var shape = ReadShape(text.Trim(), ref position);
        if (text.Trim().Length != position)
            throw new FormatException("There is more after the shape.");
        using var stream = new MemoryStream();
        using var writer = new BinaryWriter(stream);
        writer.Write(srid);
        WriteShape(writer, shape);
        return stream.ToArray();
    }

    private static void Skip(string text, ref int position)
    {
        while (position < text.Length && char.IsWhiteSpace(text[position]))
            position++;
    }

    private static void Expect(string text, ref int position, char expected)
    {
        Skip(text, ref position);
        if (position >= text.Length || text[position] != expected)
            throw new FormatException($"Expected {expected} at {position} of the shape.");
        position++;
    }

    private static bool Next(string text, ref int position, char expected)
    {
        Skip(text, ref position);
        if (position < text.Length && text[position] == expected)
        {
            position++;
            return true;
        }
        return false;
    }

    private static double[] ReadPair(string text, ref int position)
    {
        Skip(text, ref position);
        var pair = new double[2];
        for (int i = 0; i < 2; i++)
        {
            Skip(text, ref position);
            int start = position;
            while (position < text.Length && (char.IsDigit(text[position]) || text[position] is '+' or '-' or '.' or 'e' or 'E'))
                position++;
            pair[i] = double.Parse(text[start..position], Invariant);
        }
        return pair;
    }

    private static List<double[]> ReadPairs(string text, ref int position)
    {
        var points = new List<double[]> { ReadPair(text, ref position) };
        while (Next(text, ref position, ','))
            points.Add(ReadPair(text, ref position));
        return points;
    }

    private static Shape ReadLine(string text, ref int position)
    {
        Expect(text, ref position, '(');
        var line = new Shape { Kind = 2, Points = ReadPairs(text, ref position) };
        Expect(text, ref position, ')');
        return line;
    }

    private static Shape ReadPolygon(string text, ref int position)
    {
        Expect(text, ref position, '(');
        var polygon = new Shape { Kind = 3 };
        do polygon.Parts.Add(ReadLine(text, ref position)); while (Next(text, ref position, ','));
        Expect(text, ref position, ')');
        return polygon;
    }

    private static Shape ReadShape(string text, ref int position)
    {
        Skip(text, ref position);
        int start = position;
        while (position < text.Length && char.IsLetter(text[position]))
            position++;
        string word = text[start..position].ToUpperInvariant();
        var shape = new Shape();
        Skip(text, ref position);
        if (word == "GEOMETRYCOLLECTION" && string.CompareOrdinal(text, position, "EMPTY", 0, 5) == 0)
        {
            position += 5;
            shape.Kind = 7;
            return shape;
        }
        Expect(text, ref position, '(');
        switch (word)
        {
            case "POINT":
                shape.Kind = 1;
                shape.Points.Add(ReadPair(text, ref position));
                break;
            case "LINESTRING":
                shape.Kind = 2;
                shape.Points = ReadPairs(text, ref position);
                break;
            case "POLYGON":
                shape.Kind = 3;
                do shape.Parts.Add(ReadLine(text, ref position)); while (Next(text, ref position, ','));
                break;
            case "MULTIPOINT":
                shape.Kind = 4;
                do
                {
                    bool bracket = Next(text, ref position, '(');
                    shape.Parts.Add(new Shape { Kind = 1, Points = [ReadPair(text, ref position)] });
                    if (bracket)
                        Expect(text, ref position, ')');
                } while (Next(text, ref position, ','));
                break;
            case "MULTILINESTRING":
                shape.Kind = 5;
                do shape.Parts.Add(ReadLine(text, ref position)); while (Next(text, ref position, ','));
                break;
            case "MULTIPOLYGON":
                shape.Kind = 6;
                do shape.Parts.Add(ReadPolygon(text, ref position)); while (Next(text, ref position, ','));
                break;
            case "GEOMETRYCOLLECTION":
                shape.Kind = 7;
                do shape.Parts.Add(ReadShape(text, ref position)); while (Next(text, ref position, ','));
                break;
            default:
                throw new FormatException($"{word} is not a shape.");
        }
        Expect(text, ref position, ')');
        return shape;
    }

    private static void WritePoint(BinaryWriter writer, double[] point)
    {
        writer.Write(point[0]);
        writer.Write(point[1]);
    }

    private static void WriteShape(BinaryWriter writer, Shape shape)
    {
        writer.Write((byte)1);
        writer.Write((uint)shape.Kind);
        switch (shape.Kind)
        {
            case 1:
                WritePoint(writer, shape.Points[0]);
                break;
            case 2:
                writer.Write((uint)shape.Points.Count);
                foreach (var point in shape.Points)
                    WritePoint(writer, point);
                break;
            case 3:
                writer.Write((uint)shape.Parts.Count);
                foreach (var ring in shape.Parts)
                {
                    writer.Write((uint)ring.Points.Count);
                    foreach (var point in ring.Points)
                        WritePoint(writer, point);
                }
                break;
            default:
                writer.Write((uint)shape.Parts.Count);
                foreach (var part in shape.Parts)
                    WriteShape(writer, part);
                break;
        }
    }

    // ----- binary to text -----

    private static string ToText(byte[] binary)
    {
        using var reader = new BinaryReader(new MemoryStream(binary));
        reader.ReadInt32();   // the spatial reference system id belongs to the column
        return Format(ReadBinary(reader));
    }

    private static double[] ReadPoint(BinaryReader reader) => [reader.ReadDouble(), reader.ReadDouble()];

    private static List<double[]> ReadPoints(BinaryReader reader)
    {
        uint count = reader.ReadUInt32();
        var points = new List<double[]>();
        for (uint i = 0; i < count; i++)
            points.Add(ReadPoint(reader));
        return points;
    }

    private static Shape ReadBinary(BinaryReader reader)
    {
        if (reader.ReadByte() != 1)
            throw new FormatException("Only little-endian geometry is read.");
        var shape = new Shape { Kind = (int)reader.ReadUInt32() };
        switch (shape.Kind)
        {
            case 1:
                shape.Points.Add(ReadPoint(reader));
                break;
            case 2:
                shape.Points = ReadPoints(reader);
                break;
            case 3:
                uint rings = reader.ReadUInt32();
                for (uint i = 0; i < rings; i++)
                    shape.Parts.Add(new Shape { Kind = 2, Points = ReadPoints(reader) });
                break;
            default:
                uint parts = reader.ReadUInt32();
                for (uint i = 0; i < parts; i++)
                    shape.Parts.Add(ReadBinary(reader));
                break;
        }
        return shape;
    }

    private static string N(double value) => value.ToString("R", Invariant);

    private static string Pairs(List<double[]> points) => string.Join(",", points.Select(p => N(p[0]) + " " + N(p[1])));

    private static string Body(Shape shape) => shape.Kind switch
    {
        1 => Pairs(shape.Points),
        2 => "(" + Pairs(shape.Points) + ")",
        3 => string.Join(",", shape.Parts.Select(ring => "(" + Pairs(ring.Points) + ")")),
        4 => string.Join(",", shape.Parts.Select(point => "(" + Pairs(point.Points) + ")")),
        5 => string.Join(",", shape.Parts.Select(line => "(" + Pairs(line.Points) + ")")),
        6 => string.Join(",", shape.Parts.Select(polygon => "(" + string.Join(",", polygon.Parts.Select(ring => "(" + Pairs(ring.Points) + ")")) + ")")),
        _ => string.Join(",", shape.Parts.Select(Format))
    };

    private static string Format(Shape shape)
    {
        string name = shape.Kind switch { 1 => "POINT", 2 => "LINESTRING", 3 => "POLYGON", 4 => "MULTIPOINT", 5 => "MULTILINESTRING", 6 => "MULTIPOLYGON", _ => "GEOMETRYCOLLECTION" };
        if (shape.Kind == 7 && shape.Parts.Count == 0)
            return name + " EMPTY";
        return shape.Kind == 2 ? name + Body(shape) : name + "(" + Body(shape) + ")";
    }
}
""";
}

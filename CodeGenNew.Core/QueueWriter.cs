using System.Text;

namespace CodeGenNew.Core;

/// <summary> The C# of the work-queue routes (<c>QueueTables</c>): per table <c>stats</c>, <c>failed</c>, <c>claim</c> and <c>{id}/complete</c>, <c>{id}/fail</c>, <c>{id}/retry</c>. Every change of status is one guarded
/// UPDATE of the row in the status it expects, so two workers never get the same row and a late answer never overwrites a newer one. The text uses <c>§</c> tokens so the code reads as code. </summary>
public static class QueueWriter
{
    public const string WrongStateType = QueueWords.WrongStateType;

    public static string File(IReadOnlyList<QueueTable> tables, ProjectSettings project, string contextType, string[] usings)
    {
        var o = new StringBuilder();
        foreach (string u in usings)
            o.Append($"using {u};\n");
        o.Append("using Microsoft.EntityFrameworkCore;\n\n");
        o.Append(Shared.Replace("§T_STATE", WrongStateType));
        foreach (var table in tables)
            o.Append(PerTable(table, project, contextType));
        o.Append("/// <summary> Maps the queue routes of every table named in QueueTables. Generated by API_Queue. </summary>\npublic static class QueueApi\n{\n    public static void Register(WebApplication app)\n    {\n");
        foreach (var table in tables)
            o.Append($"        {table.Table.TableName}Work.Map(app);\n");
        o.Append("    }\n}\n");
        return o.ToString();
    }

    private static string PerTable(QueueTable q, ProjectSettings project, string contextType)
    {
        string By = q.ClaimedBy is null ? "" : q.ClaimedBy.CSharpName();
        string stamp = q.Claimed.CSharpBase();
        string retryType = q.Retry.CSharpBase();
        string[] values =
        [
            "§CTX", contextType, "§T", q.Table.TableName, "§R", ApiRequests.Route(q.Table), "§KT", q.Key.CSharpBase(), "§K", q.Key.CSharpName(),
            "§STATUS", q.Status.CSharpName(), "§RTT", retryType, "§RT", q.Retry.CSharpName(), "§CRT", q.Created.CSharpBase(), "§CR", q.Created.CSharpName(),
            "§CL", q.Claimed.CSharpName(), "§PR", q.Processed.CSharpName(), "§STAMP", stamp,
            "§MAX", project.QueueMaxRetries.ToString(), "§MIN", project.QueueClaimMinutes.ToString(),
            "§PENDING", QueueStatus.Pending, "§CLAIMED", QueueStatus.Claimed, "§DONE", QueueStatus.Done, "§FAILED", QueueStatus.Failed,
            "§AUTH", project.ApiAuth ? ".RequireAuthorization()" : "",
            "§ATTEMPTS", QueueWords.ClaimAttempts.ToString(), "§FAILEDROWS", QueueWords.FailedRows.ToString(), "§W_NOTCLAIMED", QueueWords.NotClaimed, "§W_NOTFAILED", QueueWords.NotFailed,
            "§SETBY", q.ClaimedBy is null ? "" : $".SetProperty(x => x.{By}, by)",
            "§CLEARBY", q.ClaimedBy is null ? "" : $".SetProperty(x => x.{By}, (string?)null)",
            "§BYLINE", q.ClaimedBy is null ? "" : $"        string? by = QueueText.Fit(worker, {Length(q.ClaimedBy)});\n",
            "§SETERROR", q.LastError is null ? "" : $".SetProperty(x => x.{q.LastError.CSharpName()}, message)",
            "§ERRORLINE", q.LastError is null ? "" : $"        string? message = QueueText.Fit(body?.Error, {Length(q.LastError)});\n"
        ];
        return Fill(Table, values);
    }

    private static int Length(ColumnModel column) => column.CharacterLength > 0 ? column.CharacterLength : int.MaxValue;

    private static string Fill(string text, params string[] pairs)
    {
        var tokens = new List<(string Token, string Value)>();
        for (int i = 0; i < pairs.Length; i += 2)
            tokens.Add((pairs[i], pairs[i + 1]));
        // longest token first, so §CL is not read as the start of §CLAIMED
        foreach (var (token, value) in tokens.OrderByDescending(t => t.Token.Length))
            text = text.Replace(token, value);
        return text;
    }

    private const string Shared = """
/// <summary> What a worker sends when it fails a row. </summary>
public sealed record QueueFailure(string? Error);

public static class QueueText
{
    public static string? Fit(string? text, int length) => text is null || text.Length <= length ? text : text[..length];
}

public static class QueueProblems
{
    public static IResult WrongState(string detail) =>
        Results.Problem(statusCode: 409, type: "§T_STATE", title: "Wrong state", detail: detail);
}

""";

    private const string Table = """
/// <summary> The work-queue routes of §T: a worker claims the oldest pending row, then completes or fails it. Generated by API_Queue. </summary>
public static class §TWork
{
    public const int MaxRetries = §MAX;
    public static readonly TimeSpan ClaimTimeout = TimeSpan.FromMinutes(§MIN);

    public sealed record Counts(int Pending, int Claimed, int Done, int Failed, §KT? OldestPendingId, DateTime? OldestPendingOn);

    private static Task<int> ReleaseStaleAsync(§CTX context)
    {
        var cutoff = DateTime.Now - ClaimTimeout;
        return context.Set<§T>().Where(x => x.§STATUS == "§CLAIMED" && x.§CL < cutoff)
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.§STATUS, "§PENDING").SetProperty(x => x.§CL, (§STAMP?)null)§CLEARBY);
    }

    private static async Task<IResult> AnswerAsync(§CTX context, §KT id, int changed, string detail)
    {
        var row = await context.Set<§T>().AsNoTracking().FirstOrDefaultAsync(x => x.§K == id);
        if (row is null)
            return Results.NotFound();
        return changed == 1 ? Results.Ok(row) : QueueProblems.WrongState(detail);
    }

    public static async Task<IResult> StatsAsync(§CTX context)
    {
        await ReleaseStaleAsync(context);
        var byStatus = await context.Set<§T>().AsNoTracking().GroupBy(x => x.§STATUS).Select(g => new { Status = g.Key, Count = g.Count() }).ToListAsync();
        int Of(string status) => byStatus.Where(g => g.Status == status).Sum(g => g.Count);
        var oldest = await context.Set<§T>().AsNoTracking().Where(x => x.§STATUS == "§PENDING").OrderBy(x => x.§CR).ThenBy(x => x.§K)
            .Select(x => new { Id = x.§K, On = x.§CR }).Take(1).ToListAsync();
        return Results.Ok(new Counts(Of("§PENDING"), Of("§CLAIMED"), Of("§DONE"), Of("§FAILED"), oldest.Select(o => (§KT?)o.Id).FirstOrDefault(), oldest.Select(o => (DateTime?)o.On).FirstOrDefault()));
    }

    public static async Task<IResult> FailedAsync(§CTX context) =>
        Results.Ok(await context.Set<§T>().AsNoTracking().Where(x => x.§STATUS == "§FAILED").OrderByDescending(x => x.§PR).ThenByDescending(x => x.§K).Take(§FAILEDROWS).ToListAsync());

    public static async Task<IResult> ClaimAsync(§CTX context, string? worker)
    {
§BYLINE        await ReleaseStaleAsync(context);
        for (int attempt = 0; attempt < §ATTEMPTS; attempt++)
        {
            var next = await context.Set<§T>().AsNoTracking().Where(x => x.§STATUS == "§PENDING").OrderBy(x => x.§CR).ThenBy(x => x.§K).Select(x => x.§K).Take(1).ToListAsync();
            if (next.Count == 0)
                return Results.NoContent();
            var id = next[0];
            var claimedOn = DateTime.Now;
            int changed = await context.Set<§T>().Where(x => x.§K == id && x.§STATUS == "§PENDING")
                .ExecuteUpdateAsync(s => s.SetProperty(x => x.§STATUS, "§CLAIMED").SetProperty(x => x.§CL, claimedOn)§SETBY);
            if (changed == 1)
                return Results.Ok(await context.Set<§T>().AsNoTracking().FirstAsync(x => x.§K == id));
        }
        return Results.NoContent();
    }

    public static async Task<IResult> CompleteAsync(§CTX context, §KT id)
    {
        var processedOn = DateTime.Now;
        int changed = await context.Set<§T>().Where(x => x.§K == id && x.§STATUS == "§CLAIMED")
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.§STATUS, "§DONE").SetProperty(x => x.§PR, processedOn));
        return await AnswerAsync(context, id, changed, "§W_NOTCLAIMED");
    }

    public static async Task<IResult> FailAsync(§CTX context, §KT id, QueueFailure? body)
    {
§ERRORLINE        var processedOn = DateTime.Now;
        int changed = await context.Set<§T>().Where(x => x.§K == id && x.§STATUS == "§CLAIMED")
            .ExecuteUpdateAsync(s => s
                .SetProperty(x => x.§STATUS, x => x.§RT + 1 >= MaxRetries ? "§FAILED" : "§PENDING")
                .SetProperty(x => x.§PR, x => x.§RT + 1 >= MaxRetries ? processedOn : (§STAMP?)null)
                .SetProperty(x => x.§CL, (§STAMP?)null)§CLEARBY§SETERROR
                .SetProperty(x => x.§RT, x => (§RTT)(x.§RT + 1))); // last: MySQL reads a column that an earlier assignment of the same UPDATE already changed
        return await AnswerAsync(context, id, changed, "§W_NOTCLAIMED");
    }

    public static async Task<IResult> RetryAsync(§CTX context, §KT id)
    {
        int changed = await context.Set<§T>().Where(x => x.§K == id && x.§STATUS == "§FAILED")
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.§STATUS, "§PENDING").SetProperty(x => x.§RT, (§RTT)0).SetProperty(x => x.§PR, (§STAMP?)null).SetProperty(x => x.§CL, (§STAMP?)null)§CLEARBY);
        return await AnswerAsync(context, id, changed, "§W_NOTFAILED");
    }

    public static void Map(WebApplication app)
    {
        app.MapGet("§R/stats", StatsAsync)§AUTH;
        app.MapGet("§R/failed", FailedAsync)§AUTH;
        app.MapPost("§R/claim", ClaimAsync)§AUTH;
        app.MapPost("§R/{id}/complete", CompleteAsync)§AUTH;
        app.MapPost("§R/{id}/fail", FailAsync)§AUTH;
        app.MapPost("§R/{id}/retry", RetryAsync)§AUTH;
    }
}

""";
}

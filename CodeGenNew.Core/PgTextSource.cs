namespace CodeGenNew.Core;

/// <summary> The C# source of the <c>PgText</c> class the generated EF Core context carries when a PostgreSQL column is an array, interval, range or geometric type: value
/// converters between the column's text (PostgreSQL's own notation, see <see cref="PgTextType"/>) and the type Npgsql maps it to. </summary>
public static class PgTextSource
{
    public const string Code = """
/// <summary> Value converters for the PostgreSQL array, interval, range and geometric columns, which the entities hold as text in PostgreSQL's own notation:
/// {1,2} for an array, 1 day 02:03:04 for an interval, [1,5) for a range, (1,2) for a point. Generated by CS_DbContext; regenerate it rather than edit it. </summary>
internal static class PgText
{
    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    /// <summary> The entity holds text, so a change is a change of the text; without this EF Core compares by the type the column is stored as, an array. </summary>
    public static readonly Microsoft.EntityFrameworkCore.ChangeTracking.ValueComparer<string> Comparer = new((a, b) => a == b, v => v.GetHashCode(), v => v);

    // ----- arrays -----

    public static ValueConverter<string, string[]> TextArray(bool nullable) =>
        new(v => ToArray(v, nullable, s => s)!, v => FromArray(v, s => s));

    public static ValueConverter<string, T[]> Array<T>(bool nullable) where T : IParsable<T> =>
        new(v => ToArray(v, nullable, Parse<T>)!, v => FromArray(v, Format));

    private static T[]? ToArray<T>(string text, bool nullable, Func<string, T> parse)
    {
        if (string.IsNullOrWhiteSpace(text))
            return nullable ? null : [];
        var items = new List<T>();
        foreach (string? item in Split(text))
            items.Add(item is null && typeof(T) == typeof(string) ? default! : parse(item ?? throw new FormatException("A NULL element is not supported for this array.")));
        return items.ToArray();
    }

    private static string FromArray<T>(T[] items, Func<T, string> format) =>
        "{" + string.Join(",", items.Select(item => item is null ? "NULL" : Quote(format(item)))) + "}";

    private static List<string?> Split(string text)
    {
        string body = text.Trim();
        if (body.Length < 2 || body[0] != '{' || body[^1] != '}')
            throw new FormatException("An array is written {a,b}.");
        body = body[1..^1];
        var items = new List<string?>();
        if (body.Trim().Length == 0)
            return items;
        var current = new StringBuilder();
        bool quoted = false, inQuotes = false;
        void End()
        {
            string value = current.ToString();
            items.Add(quoted ? value : value.Trim().Equals("NULL", StringComparison.OrdinalIgnoreCase) ? null : value.Trim());
            current.Clear();
            quoted = false;
        }
        for (int i = 0; i < body.Length; i++)
        {
            char c = body[i];
            if (inQuotes)
            {
                if (c == '\\' && i + 1 < body.Length) current.Append(body[++i]);
                else if (c == '"') inQuotes = false;
                else current.Append(c);
            }
            else if (c == '"') { current.Clear(); quoted = true; inQuotes = true; }
            else if (c == '\\' && i + 1 < body.Length) current.Append(body[++i]);
            else if (c == ',') End();
            else if (!(quoted && char.IsWhiteSpace(c))) current.Append(c);
        }
        End();
        return items;
    }

    private static string Quote(string value) =>
        value.Length == 0 || value.Equals("NULL", StringComparison.OrdinalIgnoreCase) || value.Any(c => c is '{' or '}' or ',' or '"' or '\\' || char.IsWhiteSpace(c))
            ? "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\""
            : value;

    private static T Parse<T>(string text) where T : IParsable<T> =>
        typeof(T) == typeof(bool) ? (T)(object)(text is "t" or "true" or "T" or "TRUE" ? true : text is "f" or "false" or "F" or "FALSE" ? false : throw new FormatException("A flag is t or f.")) : T.Parse(text, Invariant);

    private static string Format<T>(T value) => value switch
    {
        bool b => b ? "t" : "f",
        DateOnly d => d.ToString("yyyy-MM-dd", Invariant),
        IFormattable f => f.ToString(null, Invariant),
        _ => value?.ToString() ?? ""
    };

    // ----- interval -----

    private static readonly Regex IntervalPart = new(
        @"\G\s*(?:(?<n>[-+]?\d+(?:\.\d+)?)\s*(?<u>days?|d|hours?|h|mins?|minutes?|m|secs?|seconds?|s)\b|(?<sign>[-+]?)(?<h>\d+):(?<mi>\d{2})(?::(?<se>\d{2}(?:\.\d+)?))?)",
        RegexOptions.Compiled | RegexOptions.IgnoreCase);

    public static ValueConverter<string, TimeSpan> Interval() => new(v => ParseInterval(v), v => FormatInterval(v));

    private static TimeSpan ParseInterval(string text)
    {
        decimal ticks = 0;
        int position = 0;
        while (position < text.Length && !string.IsNullOrWhiteSpace(text[position..]))
        {
            var part = IntervalPart.Match(text, position);
            if (!part.Success || part.Length == 0)
                throw new FormatException("An interval is written 1 day 02:03:04 (days, hours, minutes and seconds; not months or years).");
            position += part.Length;
            if (part.Groups["n"].Success)
            {
                decimal amount = decimal.Parse(part.Groups["n"].Value, Invariant);
                ticks += amount * char.ToLowerInvariant(part.Groups["u"].Value[0]) switch
                {
                    'd' => TimeSpan.TicksPerDay,
                    'h' => TimeSpan.TicksPerHour,
                    'm' => TimeSpan.TicksPerMinute,
                    _ => TimeSpan.TicksPerSecond
                };
            }
            else
            {
                decimal clock = int.Parse(part.Groups["h"].Value, Invariant) * (decimal)TimeSpan.TicksPerHour + int.Parse(part.Groups["mi"].Value, Invariant) * (decimal)TimeSpan.TicksPerMinute
                    + (part.Groups["se"].Success ? decimal.Parse(part.Groups["se"].Value, Invariant) * TimeSpan.TicksPerSecond : 0);
                ticks += part.Groups["sign"].Value == "-" ? -clock : clock;
            }
        }
        return TimeSpan.FromTicks((long)decimal.Round(ticks));
    }

    private static string FormatInterval(TimeSpan value)
    {
        var parts = new List<string>();
        int days = value.Days;
        if (days != 0)
            parts.Add($"{days} day{(days == 1 ? "" : "s")}");
        var time = value - TimeSpan.FromDays(days);
        if (time != TimeSpan.Zero || days == 0)
        {
            long micro = Math.Abs(time.Ticks % TimeSpan.TicksPerSecond) / 10;
            string fraction = micro == 0 ? "" : "." + micro.ToString("000000", Invariant).TrimEnd('0');
            parts.Add($"{(time < TimeSpan.Zero ? "-" : "")}{Math.Abs(time.Hours):00}:{Math.Abs(time.Minutes):00}:{Math.Abs(time.Seconds):00}{fraction}");
        }
        return string.Join(" ", parts);
    }

    // ----- ranges -----

    private static readonly Regex RangeText = new(@"^([\[(])\s*(.*?)\s*,\s*(.*?)\s*([\])])$", RegexOptions.Compiled | RegexOptions.Singleline);

    public static ValueConverter<string, NpgsqlRange<T>> Range<T>() where T : struct, IParsable<T> =>
        new(v => ParseRange<T>(v), v => FormatRange(v));

    private static NpgsqlRange<T> ParseRange<T>(string text) where T : struct, IParsable<T>
    {
        string trimmed = text.Trim();
        if (trimmed.Equals("empty", StringComparison.OrdinalIgnoreCase))
            return NpgsqlRange<T>.Empty;
        var match = RangeText.Match(trimmed);
        if (!match.Success)
            throw new FormatException("A range is written [1,5) (a square bracket includes the end, a round one leaves it out).");
        string low = match.Groups[2].Value.Trim('"'), high = match.Groups[3].Value.Trim('"');
        return new NpgsqlRange<T>(
            low.Length == 0 ? default : T.Parse(low, Invariant), match.Groups[1].Value == "[", low.Length == 0,
            high.Length == 0 ? default : T.Parse(high, Invariant), match.Groups[4].Value == "]", high.Length == 0);
    }

    private static string FormatRange<T>(NpgsqlRange<T> range) where T : struct, IParsable<T> =>
        range.IsEmpty ? "empty"
        : (range.LowerBoundIsInclusive && !range.LowerBoundInfinite ? "[" : "(") + (range.LowerBoundInfinite ? "" : Format(range.LowerBound)) + ","
          + (range.UpperBoundInfinite ? "" : Format(range.UpperBound)) + (range.UpperBoundIsInclusive && !range.UpperBoundInfinite ? "]" : ")");

    // ----- geometric types -----

    private static readonly Regex Numbers = new(@"[-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", RegexOptions.Compiled);

    private static double[] Numeric(string text) => Numbers.Matches(text).Select(m => double.Parse(m.Value, Invariant)).ToArray();

    private static string N(double value) => value.ToString("R", Invariant);

    private static string P(NpgsqlPoint point) => $"({N(point.X)},{N(point.Y)})";

    private static List<NpgsqlPoint> Points(string text)
    {
        double[] n = Numeric(text);
        var points = new List<NpgsqlPoint>();
        for (int i = 0; i + 1 < n.Length; i += 2)
            points.Add(new NpgsqlPoint(n[i], n[i + 1]));
        return points;
    }

    public static ValueConverter<string, NpgsqlPoint> Point() => new(v => Points(v)[0], v => P(v));

    public static ValueConverter<string, NpgsqlLine> Line() =>
        new(v => new NpgsqlLine(Numeric(v)[0], Numeric(v)[1], Numeric(v)[2]), v => "{" + N(v.A) + "," + N(v.B) + "," + N(v.C) + "}");

    public static ValueConverter<string, NpgsqlLSeg> LineSegment() => new(v => new NpgsqlLSeg(Points(v)[0], Points(v)[1]), v => "[" + P(v.Start) + "," + P(v.End) + "]");

    public static ValueConverter<string, NpgsqlBox> Box() => new(v => new NpgsqlBox(Points(v)[0], Points(v)[1]), v => P(v.UpperRight) + "," + P(v.LowerLeft));

    public static ValueConverter<string, NpgsqlCircle> Circle() =>
        new(v => new NpgsqlCircle(Numeric(v)[0], Numeric(v)[1], Numeric(v)[2]), v => "<" + P(new NpgsqlPoint(v.X, v.Y)) + "," + N(v.Radius) + ">");

    public static ValueConverter<string, NpgsqlPath> Path() =>
        new(v => new NpgsqlPath(Points(v), v.TrimStart().StartsWith('[')),
            v => (v.Open ? "[" : "(") + string.Join(",", v.Select(P)) + (v.Open ? "]" : ")"));

    public static ValueConverter<string, NpgsqlPolygon> Polygon() => new(v => new NpgsqlPolygon(Points(v)), v => "(" + string.Join(",", v.Select(P)) + ")");
}
""";
}

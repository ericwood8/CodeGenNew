namespace CodeGenNew.Core;

/// <summary> The Python (FastAPI) counterpart of the asset part of <see cref="RowShapeWriter"/>: <c>app/routes/asset_files.py</c>, the upload and download routes of every table in <c>AssetTables</c>, the store
/// (<c>AssetStore</c>, a local folder by default), and the rules that keep the storage key out of a request's hands (SQLAlchemy events on the table's class). The words are <see cref="AssetWords"/>. </summary>
public static class PythonAssetWriter
{
    public static IReadOnlyList<AssetShape> Shapes(DatabaseModel database, ProjectSettings project) =>
        database.Tables.Select(t => TableShapes.For(t, project).Asset).OfType<AssetShape>().OrderBy(a => a.Table.TableName, StringComparer.OrdinalIgnoreCase).ToList();

    public static string File(IReadOnlyList<AssetShape> tables, ProjectSettings project)
    {
        var imports = new SortedSet<string>(StringComparer.Ordinal);
        var specs = new System.Text.StringBuilder();
        foreach (var a in tables)
        {
            var main = PythonTable.Of(a.Table, project);
            string Attr(ColumnModel c) => main.FieldOf(c).Name;
            imports.Add($"from app.models.{main.Module} import {main.Class}");
            imports.Add($"from app.schemas.{main.Module} import {main.Schema}");
            string url = a.Url is null ? "None" : $"\"{Attr(a.Url)}\"";
            specs.Append($"    AssetSpec(\n        route=\"{main.Route}\", row={main.Class}, schema={main.Schema},\n" +
                $"        key=\"{Attr(a.Key)}\", storage_key=\"{Attr(a.StorageKey)}\", file_name=\"{Attr(a.FileName)}\", mime=\"{Attr(a.MimeType)}\", size=\"{Attr(a.Size)}\", url={url},\n" +
                $"        name_max={Room(a.FileName)}, mime_max={Room(a.MimeType)}, url_max={(a.Url is null ? "0" : Room(a.Url))},\n    ),\n");
        }
        string folder = PythonNames.Str(project.AssetStoreFolder);
        string allowed = string.Join(", ", AssetPlan.AllowedTypes(project).Select(PythonNames.Str));
        return TemplateText.FillAll(Template, new (string, string)[]
        {
            ("§IMPORTS", string.Join("\n", imports)), ("§SPECS", specs.ToString().TrimEnd('\n')),
            ("§AUTHIMPORT\n", project.ApiAuth ? "from app.auth import require_user\n" : ""), ("§DEPS", project.ApiAuth ? "dependencies=[Depends(require_user)]" : ""),
            ("§FOLDER", folder), ("§MAXBYTES", project.AssetMaxBytes.ToString()), ("§ALLOWED", allowed), ("§UNATTACHED", AssetWords.UnattachedPrefix), ("§OCTET", AssetWords.OctetStream),
            ("§NOFILE_TYPE", AssetWords.NoFileType), ("§NOFILE", PythonNames.Str(AssetWords.NoFile)), ("§TOOLARGE_TYPE", AssetWords.TooLargeType), ("§TOOLARGE", PythonNames.Str(AssetWords.TooLarge(project.AssetMaxBytes))),
            ("§NOTALLOWED_TYPE", AssetWords.TypeNotAllowedType), ("§NOTALLOWED", PythonNames.Str(AssetWords.TypeNotAllowed(AssetPlan.AllowedTypes(project)))),
            ("§MISSING_TYPE", AssetWords.FileMissingType), ("§MISSING", PythonNames.Str(AssetWords.FileMissing))
        }) + "\n";
    }

    private static string Room(ColumnModel c) => (c.CharacterLength > 0 ? c.CharacterLength : 1000000).ToString();

    private const string Template = """"
"""The asset tables (AssetTables): rows that point at a stored file. POST <route>/upload takes a multipart form with a field named file, GET <route>/{id}/download streams it and a delete removes the file.
The same routes, sentences and problem types as the ASP.NET API (RowShapes). The row never holds the bytes; the storage key is made here and cannot be named by an ordinary save. Generated by PY_Assets."""
import os
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any, BinaryIO, Iterator
from urllib.parse import quote

from fastapi import APIRouter, Depends, File, Response, UploadFile
from fastapi.responses import StreamingResponse
from sqlalchemy import event, insert
from sqlalchemy.orm import Session, attributes, object_session

§AUTHIMPORT
from app.db import get_session
§IMPORTS
from app.support import ApiError

MAX_BYTES = §MAXBYTES
ALLOWED_TYPES = [§ALLOWED]
UNATTACHED = "§UNATTACHED"
OCTET_STREAM = "§OCTET"
NO_FILE = §NOFILE
TOO_LARGE = §TOOLARGE
NOT_ALLOWED = §NOTALLOWED
FILE_MISSING = §MISSING


class AssetStore:
    """Where the bytes of an uploaded file are kept; the row holds only the key. Replace the store with use_store() to keep files elsewhere (S3, Azure Blob)."""

    def save(self, key: str, content: BinaryIO) -> None:
        raise NotImplementedError

    def open(self, key: str) -> BinaryIO | None:
        """The file, or None when the store has none under that key."""
        raise NotImplementedError

    def delete(self, key: str) -> None:
        """Removes the file; a key with no file is not an error."""
        raise NotImplementedError


class LocalFolderAssetStore(AssetStore):
    """The default store: one file per key in a folder (ASSET_STORE_FOLDER, else AssetStoreFolder). A key that could leave the folder is refused."""

    def __init__(self, folder: str):
        self.folder = Path(folder).resolve()

    def _path(self, key: str) -> Path:
        if not is_safe_key(key):
            raise ValueError("Not a storage key.")
        return self.folder / key

    def save(self, key: str, content: BinaryIO) -> None:
        self.folder.mkdir(parents=True, exist_ok=True)
        with open(self._path(key), "xb") as target:
            while chunk := content.read(81920):
                target.write(chunk)

    def open(self, key: str) -> BinaryIO | None:
        path = self._path(key)
        return open(path, "rb") if path.is_file() else None

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


store: AssetStore = LocalFolderAssetStore(os.environ.get("ASSET_STORE_FOLDER", §FOLDER))


def use_store(new_store: AssetStore) -> None:
    """Keeps the files in another store."""
    global store
    store = new_store


def is_safe_key(key: str) -> bool:
    return 0 < len(key) <= 200 and key[0] != "." and ".." not in key and all(c.isascii() and (c.isalnum() or c in "-_.") for c in key)


def make_key(file_name: str | None) -> str:
    extension = Path(file_name or "").suffix.lower()
    if not 2 <= len(extension) <= 9 or not all(c.isascii() and c.isalnum() for c in extension[1:]):
        extension = ""
    return uuid.uuid4().hex + extension


def clean_type(content_type: str | None) -> str:
    text = (content_type or "").split(";")[0].strip().lower()
    return text if "/" in text and len(text) <= 100 else OCTET_STREAM


def clean_name(name: str | None, limit: int) -> str:
    text = (name or "").replace("\\", "/").split("/")[-1]
    text = "".join(c for c in text if c.isprintable()).strip()
    return (text or "file")[:limit]


def accepts(mime: str) -> bool:
    if not ALLOWED_TYPES:
        return True
    return any(mime.startswith(a[:-1]) if a.endswith("/*") else a == mime for a in ALLOWED_TYPES)



def keep_storage_in_the_server(spec: AssetSpec) -> None:
    """A row made by the ordinary create holds an unattached key, an update keeps the stored key, type and size, and a delete removes the file once the delete is committed."""

    @event.listens_for(spec.row, "before_insert")
    def unattached_key(mapper, connection, target):
        setattr(target, spec.storage_key, UNATTACHED + uuid.uuid4().hex)

    @event.listens_for(spec.row, "before_update")
    def stored_key(mapper, connection, target):
        for name in (spec.storage_key, spec.mime, spec.size):
            history = attributes.get_history(target, name)
            if history.deleted:
                setattr(target, name, history.deleted[0])

    @event.listens_for(spec.row, "after_delete")
    def file_to_remove(mapper, connection, target):
        key = getattr(target, spec.storage_key)
        session = object_session(target)
        if session is not None and key and not key.startswith(UNATTACHED) and is_safe_key(key):
            session.info.setdefault("asset_files_gone", []).append(key)


@event.listens_for(Session, "after_commit")
def remove_files_of_deleted_rows(session):
    for key in session.info.pop("asset_files_gone", []):
        try:
            store.delete(key)
        except OSError:
            pass


@event.listens_for(Session, "after_rollback")
def keep_files_of_rolled_back_deletes(session):
    session.info.pop("asset_files_gone", None)


def file_size(upload: UploadFile) -> int:
    if upload.size is not None:
        return upload.size
    upload.file.seek(0, os.SEEK_END)
    size = upload.file.tell()
    upload.file.seek(0)
    return size


def stream(opened: BinaryIO) -> Iterator[bytes]:
    try:
        while chunk := opened.read(81920):
            yield chunk
    finally:
        opened.close()


def add_routes(spec: AssetSpec) -> None:
    @router.post(f"{spec.route}/upload", status_code=201, response_model=spec.schema)
    def upload(response: Response, file: UploadFile | None = File(None), session: Session = Depends(get_session)):
        """Takes a multipart form with a field named file, checks its size and type, writes it to the store under a key made here and answers the new row."""
        size = 0 if file is None else file_size(file)
        if file is None or size == 0:
            raise ApiError(400, "No file", problem_type="§NOFILE_TYPE", detail=NO_FILE)
        if size > MAX_BYTES:
            raise ApiError(413, "File too large", problem_type="§TOOLARGE_TYPE", detail=TOO_LARGE)
        mime = clean_type(file.content_type)
        if not accepts(mime):
            raise ApiError(415, "File type not allowed", problem_type="§NOTALLOWED_TYPE", detail=NOT_ALLOWED)
        key = make_key(file.filename)
        file.file.seek(0)
        store.save(key, file.file)
        values = {spec.storage_key: key, spec.file_name: clean_name(file.filename, spec.name_max), spec.mime: mime[: spec.mime_max], spec.size: size}
        try:
            # a Core insert of these columns only: the database fills the others with their defaults, and the key rule of the ordinary create does not apply
            result = session.execute(insert(spec.row.__table__).values({getattr(spec.row, name).property.columns[0]: value for name, value in values.items()}))
            row = session.get(spec.row, result.inserted_primary_key[0])
            if spec.url is not None:
                setattr(row, spec.url, f"{spec.route}/{getattr(row, spec.key)}/download"[: spec.url_max])
            session.commit()
        except Exception:
            session.rollback()
            store.delete(key)
            raise
        session.refresh(row)
        response.headers["Location"] = f"{spec.route}/{getattr(row, spec.key)}"
        return row

    @router.get(f"{spec.route}/{{id}}/download")
    def download(id: int, session: Session = Depends(get_session)):
        """Streams the file as a download; 404 for a missing row, and a problem when the store has no file for the row."""
        row = session.get(spec.row, id)
        if row is None:
            raise ApiError(404, "Not found.")
        key = getattr(row, spec.storage_key)
        opened = None if key.startswith(UNATTACHED) or not is_safe_key(key) else store.open(key)
        if opened is None:
            raise ApiError(404, "File missing", problem_type="§MISSING_TYPE", detail=FILE_MISSING)
        name = getattr(row, spec.file_name)
        fallback = "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else "_" for c in name)
        headers = {"Content-Disposition": f"attachment; filename=\"{fallback}\"; filename*=UTF-8''{quote(name)}", "X-Content-Type-Options": "nosniff"}
        return StreamingResponse(stream(opened), media_type=getattr(row, spec.mime) or OCTET_STREAM, headers=headers)


for _spec in SPECS:
    keep_storage_in_the_server(_spec)
    add_routes(_spec)
"""";
}

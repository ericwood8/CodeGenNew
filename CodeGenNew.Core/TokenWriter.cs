/// <summary> The C# of the token routes (<c>TokenTables</c>): per table <c>GET</c> (the rows without the hash, for an administrator), <c>{id}/revoke</c>, <c>revoke-person/{personId}</c> and <c>spend</c>, and the
/// <c>IssueAsync</c> and <c>SpendAsync</c> an application's own sign-in or reset code calls. The token itself is never stored or answered: the row holds its SHA-256 in hex. Every change is one guarded UPDATE of the row
/// that is still active, so a token is spent once even when two requests present it at the same moment. The text uses <c>§</c> tokens so the code reads as code. </summary>
public static class TokenWriter
{
    public static string File(IReadOnlyList<TokenShape> tables, ProjectSettings project, string contextType, string[] usings)
    {
        var o = new StringBuilder();
        foreach (string u in usings)
            o.Append($"using {u};\n");
        o.Append("using System.Security.Claims;\nusing System.Security.Cryptography;\nusing System.Text;\nusing Microsoft.EntityFrameworkCore;\n\n");
        o.Append(Fill(Shared, "§T_SPEND", TokenWords.SpendType, "§W_SPENDTITLE", TokenWords.SpendTitle, "§W_SPENDDETAIL", TokenWords.SpendDetail,
            "§T_ROLE", ProblemTypes.RoleNotAllowed, "§W_ADMINTITLE", TokenWords.AdminsTitle, "§W_ADMINDETAIL", TokenWords.AdminsDetail));
        foreach (var table in tables.OrderBy(t => t.Table.TableName, StringComparer.OrdinalIgnoreCase))
            o.Append(PerTable(table, contextType));
        o.Append("/// <summary> Maps the token routes of every table named in TokenTables. Generated by API_Token. </summary>\npublic static class TokenApi\n{\n    public static void Register(WebApplication app)\n    {\n");
        foreach (var table in tables.OrderBy(t => t.Table.TableName, StringComparer.OrdinalIgnoreCase))
            o.Append($"        {table.Table.TableName}Tokens.Map(app);\n");
        o.Append("    }\n}\n");
        return o.ToString();
    }

    /// <summary> The test that a row is still active, over a row <c>x</c> and a variable <c>now</c>. </summary>
    public static string ActiveTest(TokenShape t) =>
        string.Join(" && ", t.Ends.Select(c => c.IsBooleanColumn ? $"!x.{c.CSharpName()}" : $"x.{c.CSharpName()} == null").Prepend($"x.{t.Expiry.CSharpName()} > now"));

    /// <summary> The assignment that ends a row, for <c>ExecuteUpdateAsync(s =&gt; s...)</c>, over a variable <c>now</c>: a spend sets the used column, a revoke the revoked column. </summary>
    public static string EndClause(TokenShape t, bool spending = false)
    {
        var end = spending ? t.Spent : t.Revoked;
        return end is null ? $".SetProperty(x => x.{t.Expiry.CSharpName()}, now)" : end.IsBooleanColumn ? $".SetProperty(x => x.{end.CSharpName()}, true)" : $".SetProperty(x => x.{end.CSharpName()}, now)";
    }

    private static string PerTable(TokenShape t, string contextType)
    {
        string active = ActiveTest(t), end = EndClause(t);
        string fields = string.Join(", ", t.Shown.Select(c => $"x.{c.CSharpName()}")) + $", Active = {active}";
        var person = t.Person;
        var family = t.Family;
        string familyType = family?.CSharpBase() ?? "string";
        string personType = person?.CSharpBase() ?? "int";
        string personName = person?.CSharpName() ?? "";
        string key = t.Key.CSharpName();
        string route = ApiRequests.Route(t.Table);
        string[] values =
        [
            "§CTX", contextType, "§T", t.Table.TableName, "§R", route, "§KT", t.Key.CSharpBase(), "§K", key,
            "§H", t.Hash.CSharpName(), "§E", t.Expiry.CSharpName(), "§ACTIVE", active, "§END", end, "§FIELDS", fields, "§ROWS", TokenWords.ListRows.ToString(),
            "§SPENTPERSON", person is null ? "" : $", {personType}? PersonId",
            "§SPENTFAMILY", family is null ? "" : $", {familyType}? Family",
            "§SELECTPERSON", person is null ? "" : $", PersonId = ({personType}?)x.{personName}",
            "§SELECTFAMILY", family is null ? "" : $", Family = ({familyType}?)x.{family.CSharpName()}",
            "§NEWSPENT", $"new Spent(found.{key}{(person is null ? "" : ", found.PersonId")}{(family is null ? "" : ", found.Family")})",
            "§SPENDEND", EndClause(t, spending: true),
            "§SPENDAUTH", t.Anonymous ? "AllowAnonymous" : "RequireAuthorization",
            "§REUSE", family is null ? "" : $"        if (found.Live && found.Family is not null)\n            await context.Set<§T>().Where(x => x.{family.CSharpName()} == found.Family && {active}).ExecuteUpdateAsync(s => s{end});\n",
            "§TESTFAMILYARG", family is null ? "" : $", {familyType}? family = null",
            "§TESTFAMILY", family is null ? "" : $"            if (family is not null)\n                row.{family.CSharpName()} = family{(family.IsStringColumn ? "" : ".Value")};\n",
            "§PERSONROUTE", person is null ? "" : PersonRoute(personType, personName),
            "§PERSONMAP", person is null ? "" : $"        app.MapPost(\"{route}/revoke-person/{{personId}}\", RevokePersonAsync).RequireAuthorization();\n",
            "§PERSONFILTER", person is null ? "" : $"        if (personId is not null)\n            query = query.Where(x => x.{personName} == personId);\n",
            "§LISTARGS", person is null ? "" : $", {personType}? personId",
            "§TESTARGS", person is null ? "" : $", {personType}? person = null",
            "§TESTFILL", TestFill(t),
            "§TESTRESET", string.Concat(t.Ends.Select(c => $"            row.{c.CSharpName()} = {(c.IsBooleanColumn ? "false" : "null")};\n")),
            "§TESTPERSON", person is null ? "" : $"            if (person is not null)\n                row.{personName} = person.Value;\n",
            "§PERSONLOOKUP", person is null ? "" : PersonLookup(t, personType)
        ];
        return Fill(Fill(Table, values), values);
    }

    /// <summary> What the test support does for a table with no row to copy: a value for every column that cannot be NULL, or a sentence that says a row is needed. </summary>
    private static string TestFill(TokenShape t)
    {
        var fill = TokenPlan.RequiredFill(t);
        string body = fill is null
            ? $"throw new InvalidOperationException(\"Add a row to {t.Table.TableName} for the tests to copy: its other required columns need values the generator cannot invent.\");"
            : string.Join(" ", fill);
        return fill is { Count: 0 } ? "" : $"            else\n            {{\n                {body}\n            }}\n";
    }


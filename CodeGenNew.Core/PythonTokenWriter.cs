using System.Text;

namespace CodeGenNew.Core;

/// <summary> The Python (FastAPI) counterpart of <see cref="TokenWriter"/>: <c>app/routes/tokens.py</c>, the list without the hash, <c>{id}/revoke</c>, <c>revoke-person/{personId}</c> and <c>spend</c> of every table in <c>TokenTables</c>, with the same
/// sentences (<see cref="TokenWords"/>), problem type and status codes. A token table has no model, so each table is a SQLAlchemy <c>table()</c> of the columns the routes use. Every change is one UPDATE of the row that is still active. </summary>
public static class PythonTokenWriter
{
    public static string File(IReadOnlyList<TokenShape> tables, ProjectSettings project)
    {
        var specs = new StringBuilder();
        foreach (var t in tables)
        {
            string Col(ColumnModel c) => SqlAlchemyType(c) is { } type ? $"column(\"{c.DbName}\", {type})" : $"column(\"{c.DbName}\")";
            string shown = string.Join(", ", t.Shown.Select(c => $"(\"{JsonNames.Camel(c.Name)}\", \"{c.DbName}\")"));
            specs.Append($"    TokenSpec(\n        route=\"{BlazorNames.ApiRoute(t.Table.TableName)}\", name=\"{t.Table.TableName}\",\n" +
                $"        table=table(\"{t.Table.DbTableName}\", {string.Join(", ", t.Table.Columns.Select(Col))}),\n" +
                $"        key=\"{t.Key.DbName}\", hash=\"{t.Hash.DbName}\", expiry=\"{t.Expiry.DbName}\",\n" +
                $"        ends=[{string.Join(", ", t.Ends.Select(End))}], revoke_end={(t.Revoked is null ? "None" : End(t.Revoked))}, spend_end={(t.Spent is null ? "None" : End(t.Spent))},\n" +
                $"        person={(t.Person is null ? "None" : $"\"{t.Person.DbName}\"")}, family={(t.Family is null ? "None" : $"\"{t.Family.DbName}\"")}, anonymous={(t.Anonymous ? "True" : "False")},\n        shown=[{shown}],\n    ),\n");
        }
        return TemplateText.FillAll(Template, new (string, string)[]
        {
            ("§SPECS", specs.ToString().TrimEnd('\n')), ("§T_SPEND", TokenWords.SpendType), ("§W_SPENDTITLE", PythonNames.Str(TokenWords.SpendTitle)), ("§W_SPENDDETAIL", PythonNames.Str(TokenWords.SpendDetail)),
            ("§W_ADMINTITLE", PythonNames.Str(TokenWords.AdminsTitle)), ("§W_ADMINDETAIL", PythonNames.Str(TokenWords.AdminsDetail)), ("§ROWS", TokenWords.ListRows.ToString()),
            ("§FORBIDDEN", HttpStatus.Forbidden.ToString()), ("§BADREQUEST", HttpStatus.BadRequest.ToString()), ("§NOTFOUND", HttpStatus.NotFound.ToString())
        });
    }

    private static string End(ColumnModel c) => $"(\"{c.DbName}\", {(c.IsBooleanColumn ? "True" : "False")})";

    private static string? SqlAlchemyType(ColumnModel c) =>
        c.IsBooleanColumn ? "Boolean" : LogTablePlan.HasTimeOfDay(c) ? "DateTime" : c.IsIntegerColumn ? "Integer" : c.IsStringColumn ? "String" : null;

    private const string Template = """"
"""The session and token tables (TokenTables): an administrator's list without the hash, revoke, sign a person out everywhere, and spend a token once. The same routes, sentences and problem type as the ASP.NET API (API_Token).
The row holds the SHA-256 of the token in hex, never the token. Every change is one UPDATE of the row that is still active, so a token is spent once. Generated by PY_Token."""
import hashlib
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from fastapi import APIRouter, Depends, Query
from pydantic import BaseModel
from sqlalchemy import Boolean, DateTime, Integer, String, and_, column, false, or_, select, table, update
from sqlalchemy.orm import Session

from app.auth import PROBLEM_ROLE_NOT_ALLOWED, CurrentUser, require_user
from app.db import get_session
from app.support import ApiError

PROBLEM_NOT_VALID = "§T_SPEND"
LIST_ROWS = §ROWS


class TokenSpend(BaseModel):
    """What a caller sends to spend a token."""

    token: str | None = None


@dataclass(frozen=True)
class TokenSpec:
    """One table of TokenTables: the columns the routes use. ends are the used and revoked columns as (name, is a yes/no flag); revoke_end and spend_end are the one a revoke and a spend set (None: the expiry is set to now)."""

    route: str
    name: str
    table: Any
    key: str
    hash: str
    expiry: str
    ends: list[tuple[str, bool]]
    revoke_end: tuple[str, bool] | None
    spend_end: tuple[str, bool] | None
    person: str | None
    family: str | None
    anonymous: bool
    shown: list[tuple[str, str]]

    def col(self, name: str) -> Any:
        return self.table.c[name]


SPECS = [
§SPECS
]


def token_hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def administrator_only(user: CurrentUser = Depends(require_user)) -> None:
    if not user.is_admin:
        raise ApiError(§FORBIDDEN, §W_ADMINTITLE, problem_type=PROBLEM_ROLE_NOT_ALLOWED, detail=§W_ADMINDETAIL)


def active_test(spec: TokenSpec, now: datetime) -> Any:
    tests = [spec.col(spec.expiry) > now]
    for name, flag in spec.ends:
        end = spec.col(name)
        tests.append(end == false() if flag else end.is_(None))
    return and_(*tests)


def end_values(spec: TokenSpec, now: datetime, spending: bool = False) -> dict[str, Any]:
    end = spec.spend_end if spending else spec.revoke_end
    if end is None:
        return {spec.expiry: now}
    name, flag = end
    return {name: True if flag else now}


def describe(spec: TokenSpec, row: Any, now: datetime) -> dict[str, Any]:
    values = row._mapping
    answer = {json: values[db] for json, db in spec.shown}
    ended = any(bool(values[name]) if flag else values[name] is not None for name, flag in spec.ends)
    answer["active"] = values[spec.expiry] > now and not ended
    return answer


def spend(session: Session, spec: TokenSpec, token: str | None) -> dict[str, Any] | None:
    """One UPDATE of the row that is still active: None when the token is not known, was used or revoked, or has expired. With a family column, a token that was already used ends every active token of its family."""
    if not token:
        return None
    digest = token_hash(token)
    now = datetime.now()
    hash_column = spec.col(spec.hash)
    columns = [spec.col(spec.key), spec.col(spec.expiry)] + [spec.col(name) for name in (spec.person, spec.family) if name]
    found = session.execute(select(*columns).where(or_(hash_column == digest, hash_column == digest.upper()))).first()
    if found is None:
        return None
    values = found._mapping
    key = values[spec.key]
    changed = session.execute(update(spec.table).where(spec.col(spec.key) == key, active_test(spec, now)).values(end_values(spec, now, True))).rowcount
    if changed != 1:
        if spec.family and values[spec.family] is not None and values[spec.expiry] > now:
            session.execute(update(spec.table).where(spec.col(spec.family) == values[spec.family], active_test(spec, now)).values(end_values(spec, now)))
        session.commit()
        return None
    session.commit()
    answer: dict[str, Any] = {"id": key}
    if spec.person:
        answer["personId"] = values[spec.person]
    if spec.family:
        answer["family"] = values[spec.family]
    return answer


router = APIRouter()
public_router = APIRouter()   # the spend routes of the tables in TokenAnonymousSpend: main.py includes it without the sign-in check


def add_routes(spec: TokenSpec) -> None:
    @router.get(spec.route, name=spec.name + "TokenList", dependencies=[Depends(administrator_only)])
    def list_route(person_id: int | None = Query(None, alias="personId"), session: Session = Depends(get_session)):
        now = datetime.now()
        query = select(spec.table)
        if person_id is not None and spec.person:
            query = query.where(spec.col(spec.person) == person_id)
        rows = session.execute(query.order_by(spec.col(spec.key).desc()).limit(LIST_ROWS)).all()
        return [describe(spec, row, now) for row in rows]

    @(public_router if spec.anonymous else router).post(spec.route + "/spend", name=spec.name + "TokenSpend")
    def spend_route(body: TokenSpend | None = None, session: Session = Depends(get_session)):
        answer = spend(session, spec, body.token if body else None)
        if answer is None:
            raise ApiError(§BADREQUEST, §W_SPENDTITLE, problem_type=PROBLEM_NOT_VALID, detail=§W_SPENDDETAIL)
        return answer

    @router.post(spec.route + "/{id}/revoke", name=spec.name + "TokenRevoke", dependencies=[Depends(administrator_only)])
    def revoke_route(id: int, session: Session = Depends(get_session)):
        now = datetime.now()
        session.execute(update(spec.table).where(spec.col(spec.key) == id, active_test(spec, now)).values(end_values(spec, now)))
        session.commit()
        row = session.execute(select(spec.table).where(spec.col(spec.key) == id)).first()
        if row is None:
            raise ApiError(§NOTFOUND, "Not found.")
        return describe(spec, row, now)

    if spec.person:

        @router.post(spec.route + "/revoke-person/{person_id}", name=spec.name + "TokenRevokePerson", dependencies=[Depends(administrator_only)])
        def revoke_person_route(person_id: int, session: Session = Depends(get_session)):
            now = datetime.now()
            changed = session.execute(update(spec.table).where(spec.col(spec.person) == person_id, active_test(spec, now)).values(end_values(spec, now))).rowcount
            session.commit()
            return {"revoked": changed}


for _spec in SPECS:
    add_routes(_spec)
"""";
}

/// <summary> The C# of the inbound event routes (<c>InboundTables</c>): per table <c>POST receive</c> and <c>POST receive/{source}</c> (open to anyone, a signature instead of a login, a replay window, a size limit, an event id applied once, the
/// raw body kept as text), <c>GET unprocessed</c> and <c>POST {id}/processed</c> (for the signed-in worker). The text uses <c>§</c> tokens so the code reads as code. </summary>
public static class InboundWriter
{
    public static string File(IReadOnlyList<InboundShape> tables, ProjectSettings project, string contextType, string[] usings)
    {
        var o = new StringBuilder();
        foreach (string u in usings)
            o.Append($"using {u};\n");
        o.Append("using Microsoft.EntityFrameworkCore;\n\n");
        foreach (var table in tables)
            o.Append(PerTable(table, project, contextType));
        o.Append("/// <summary> Maps the inbound routes of every table named in InboundTables. Generated by API_Inbound. </summary>\npublic static class InboundApi\n{\n    public static void Register(WebApplication app)\n    {\n");
        foreach (var table in tables)
            o.Append($"        {table.Table.TableName}Inbound.Map(app);\n");
        o.Append("    }\n}\n");
        return o.ToString();
    }


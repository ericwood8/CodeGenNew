    private static string RaceLine(InboundShape q) =>
        $"            if (eventId is {{ Length: > 0 }} && await FindAsync(context, eventId, {(q.Source is null ? "null" : "sourceText")}) is {{ }} winner)\n                return Results.Ok(new {{ received = false, duplicate = true, id = winner }});\n";

    private static string FindEvent(InboundShape q) => q.EventId is null ? "" :
        "\n" + JsonEventIdText + $"\n    private static Task<§KT?> FindAsync(§CTX context, string eventId, string? source) =>\n        context.Set<§T>().AsNoTracking().Where(x => x.{q.EventId.CSharpName()} == eventId{(q.Source is null ? "" : $" && x.{q.Source.CSharpName()} == source")})\n            .Select(x => (§KT?)x.§K).FirstOrDefaultAsync();\n";

    private static string EventLine(InboundShape q) =>
        $"        string? eventId = http.Request.Headers[\"{InboundWords.EventHeader}\"].ToString() is {{ Length: > 0 }} header ? header : JsonEventId(body);\n" +
        $"        if (eventId is {{ Length: > {Length(q.EventId!)} }})\n            eventId = eventId[..{Length(q.EventId!)}];\n" +
        $"        if (eventId is {{ Length: > 0 }} && await FindAsync(context, eventId, {(q.Source is null ? "null" : "sourceText")}) is {{ }} existing)\n" +
        "            return Results.Ok(new { received = false, duplicate = true, id = existing });\n";

    private static int Length(ColumnModel column) => column.CharacterLength > 0 ? column.CharacterLength : int.MaxValue;

    private static string Fill(string text, params string[] pairs)
    {
        var tokens = new List<(string Token, string Value)>();
        for (int i = 0; i < pairs.Length; i += 2)
            tokens.Add((pairs[i], pairs[i + 1]));
        // the pieces built above hold tokens of their own
        string[] pieces = ["§FINDEVENT", "§EVENTIDLINE", "§RACELINE"];
        foreach (string piece in pieces)
            text = text.Replace(piece, pairs[Array.IndexOf(pairs, piece) + 1]);
        string filled = TemplateText.FillAll(text, [.. tokens.Where(t => !pieces.Contains(t.Token))]);
        return filled;
    }


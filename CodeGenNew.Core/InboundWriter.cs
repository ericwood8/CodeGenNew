        return Fill(table + "\n" + support + "\n", [.. clientValues, .. values]);
    }

    private static string SourceSecretsText(ProjectSettings project) =>
        InboundPlan.SourceSecrets(project) is { Count: > 0 } own
            ? "\n    private static readonly (string Source, string Secret)[] SourceSecrets = [" + string.Join(", ", own.Select(s => $"(\"{s.Source}\", \"{s.Secret}\")")) + "];"
            : "";

    private static string SecretLine(ProjectSettings project) =>
        InboundPlan.SourceSecrets(project).Count == 0
            ? $"        string? secret = configuration[\"{project.InboundSecret}\"];\n"
            : $"        string secretName = \"{project.InboundSecret}\";\n        foreach (var own in SourceSecrets)\n        {{\n            if (source is not null && string.Equals(own.Source, source, StringComparison.OrdinalIgnoreCase))\n            {{\n                secretName = own.Secret;\n                source = own.Source;\n            }}\n        }}\n        string? secret = configuration[secretName];\n";


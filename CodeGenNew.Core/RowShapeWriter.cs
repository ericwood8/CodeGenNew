using System.Text;

namespace CodeGenNew.Core;

/// <summary> The C# of the row-shape checks and routes (<c>TreeTables</c>, <c>SoftDeleteTables</c>, <c>EffectiveDatedTables</c>): per table a static <c>&lt;Table&gt;Shape</c> class the table's API calls before a save and before a delete
/// (<c>CheckSaveAsync</c>, <c>CheckDeleteAsync</c>) and that maps the extra routes. The text uses <c>§</c> tokens so the code reads as code. </summary>
public static class RowShapeWriter
{
    /// <summary> Whether the table's API has to call <c>CheckSaveAsync</c>. </summary>
    public static bool HasSaveCheck(TableModel table, ProjectSettings project) => TableShapes.For(table, project).Tree is not null || TableShapes.For(table, project).Content is not null || TableShapes.For(table, project).Asset is not null || TableShapes.For(table, project).Effective is not null || TableShapes.For(table, project).DefaultRow is not null || SnapshotPlan.IsListed(table.TableName, project) || PolymorphicPlan.IsLinkTable(table.TableName, project);

    /// <summary> Whether the table's API has to call <c>CheckDeleteAsync</c>. </summary>
    public static bool HasDeleteCheck(TableModel table, ProjectSettings project) => TableShapes.For(table, project).Tree is not null || TableShapes.For(table, project).SoftDelete is not null || TableShapes.For(table, project).Asset is not null || TableShapes.For(table, project).DefaultRow is not null || PolymorphicPlan.RefusesDeleteOf(table.TableName, project);

    /// <summary> Whether the table's API has to call <c>AfterDeleteAsync</c> (an asset table removes its file, a linked table may remove its links). </summary>
    public static bool HasAfterDelete(TableModel table, ProjectSettings project) => TableShapes.For(table, project).Asset is not null || PolymorphicPlan.RemovesLinksOf(table.TableName, project);

    public static string File(DatabaseModel database, ProjectSettings project, string contextType, string[] usings)
    {
        var tables = database.Tables.Where(t => RowShapePlan.Has(t, project)).OrderBy(t => t.TableName, StringComparer.OrdinalIgnoreCase).ToList();
        var o = new StringBuilder();
        foreach (string u in usings)
            o.Append($"using {u};\n");
        o.Append("using Microsoft.AspNetCore.Mvc;\nusing Microsoft.EntityFrameworkCore;\n\n");
        o.Append(Shared.Replace("§TREE_CYCLE", RowShapeWords.TreeCycleType).Replace("§TREE_DEEP", RowShapeWords.TreeTooDeepType).Replace("§TREE_CHILDREN", RowShapeWords.TreeHasChildrenType)
            .Replace("§EFF_RANGE", RowShapeWords.EffectiveRangeType).Replace("§EFF_OVERLAP", RowShapeWords.EffectiveOverlapType).Replace("§NOT_DELETED", RowShapeWords.NotDeletedType).Replace("§SNAP_PARENT", RowShapeWords.SnapshotParentType).Replace("§SNAP_TITLE", RowShapeWords.SnapshotParentTitle).Replace("§SLUG_TAKEN", ContentWords.SlugTakenType));
        if (project.PolymorphicLinks.Length > 0)
            o.Append(LinkShared.Replace("§UNKNOWN_TYPE", LinkWords.UnknownTypeType).Replace("§MISSING_TYPE", LinkWords.TargetMissingType).Replace("§INUSE_TYPE", LinkWords.TargetInUseType));
        if (project.DefaultRowTables.Length > 0)
            o.Append(DefaultRowShared);
        if (tables.Any(t => TableShapes.For(t, project).Asset is not null))
            o.Append(AssetShared(project));
        foreach (var table in tables)
            o.Append(PerTable(table, project, contextType, database));
        o.Append("/// <summary> Maps the extra routes of every table named in TreeTables, ContentTables, AssetTables, PolymorphicLinks, DefaultRowTables, SoftDeleteTables or EffectiveDatedTables. Generated by API_RowShapes. </summary>\npublic static class RowShapeApi\n{\n    public static void Register(WebApplication app)\n    {\n");
        foreach (var table in tables)
            o.Append($"        {table.TableName}Shape.Map(app);\n");
        o.Append("    }\n}\n");
        return o.ToString();
    }

    private static string PerTable(TableModel table, ProjectSettings project, string contextType, DatabaseModel database)
    {
        var dialect = database.Dialect;
        var tree = TableShapes.For(table, project).Tree;
        var soft = TableShapes.For(table, project).SoftDelete;
        var effective = TableShapes.For(table, project).Effective;
        var key = table.PrimaryKeyColumns[0];
        string keyType = key.CSharpBase();
        string route = ApiRequests.Route(table);
        string auth = project.ApiAuth ? ".RequireAuthorization()" : "";
        string admin = project.ApiAuth ? ".RequireAuthorization().RequireWriteRoles([AuthNames.AdminRole])" : "";
        var o = new StringBuilder();
        var maps = new StringBuilder();
        var save = new StringBuilder();
        var delete = new StringBuilder();

        string Fill(string text, params (string Token, string Value)[] extra)
        {
            var values = new List<(string Token, string Value)>
            {
                ("§CTX", contextType), ("§T", table.TableName), ("§KT", keyType), ("§K", key.CSharpName()), ("§R", route), ("§AUTH", auth), ("§ADMIN", admin)
            };
            values.AddRange(extra);
            return TemplateText.FillAll(text, [.. values]);
        }

        o.Append(Fill("/// <summary> The row-shape checks and routes of §T (" + string.Join(", ", new[] { tree is null ? null : "TreeTables", TableShapes.For(table, project).Content is null ? null : "ContentTables", TableShapes.For(table, project).Asset is null ? null : "AssetTables", soft is null ? null : "SoftDeleteTables", effective is null ? null : "EffectiveDatedTables", PolymorphicPlan.IsLinkTable(table.TableName, project) || PolymorphicPlan.IsTarget(table.TableName, project) ? "PolymorphicLinks" : null }.OfType<string>())
            + "): the table's API calls CheckSaveAsync before it saves a row and CheckDeleteAsync before it deletes one. Generated by API_RowShapes. </summary>\npublic static class §TShape\n{\n"));

        if (tree is not null)
        {
            string parent = tree.Parent.CSharpName(), parentType = tree.Parent.CSharpBase();
            string text = tree.Text is null ? "" : tree.Text.CSharpName();
            string textValue = tree.Text is null ? "r.Id.ToString()" : tree.Text.IsNullable ? "r.Text ?? \"\"" : "r.Text";
            string textSelect = tree.Text is null ? "" : $", Text = x.{text}";
            string[] values = ["§P", parent, "§PT", parentType, "§MAX", tree.MaxDepth.ToString(), "§TEXTSELECT", textSelect, "§TEXTVALUE", textValue,
                "§W_OWN", RowShapeWords.OwnParent, "§W_UNDER", RowShapeWords.UnderItself, "§W_CHILDREN", RowShapeWords.HasChildren, "§W_DEEP", RowShapeWords.TooDeep(tree.MaxDepth)];
            o.Append(Fill(Tree, Pairs(values)));
            save.Append("        if (await CheckTreeAsync(context, row) is { } treeProblem)\n            return treeProblem;\n");
            delete.Append("        if (await CheckChildrenAsync(context, id) is { } childrenProblem)\n            return childrenProblem;\n");
            maps.Append(Fill("        app.MapGet(\"§R/tree\", TreeAsync)§AUTH;\n        app.MapPost(\"§R/{id}/promote-children\", PromoteChildrenAsync)§AUTH;\n"));
        }

        if (soft is not null)
        {
            string flag = soft.Flag.CSharpName();
            string setOn = soft.DeletedOn is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedOn.CSharpName()}, now)";
            string setBy = soft.DeletedBy is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedBy.CSharpName()}, by)";
            string clearOn = soft.DeletedOn is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedOn.CSharpName()}, ({soft.DeletedOn.CSharpBase()}?)null)";
            string clearBy = soft.DeletedBy is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedBy.CSharpName()}, (string?)null)";
            string order = soft.DeletedOn is null ? ".OrderByDescending(x => x." + key.CSharpName() + ")" : $".OrderByDescending(x => x.{soft.DeletedOn.CSharpName()}).ThenByDescending(x => x.{key.CSharpName()})";
            string byLine = soft.DeletedBy is null ? "" : $"        string? by = caller?.Identity?.Name is {{ }} name ? (name.Length <= {(soft.DeletedBy.CharacterLength > 0 ? soft.DeletedBy.CharacterLength : 1000000)} ? name : name[..{(soft.DeletedBy.CharacterLength > 0 ? soft.DeletedBy.CharacterLength : 1000000)}]) : null;\n";
            // IgnoreQueryFilters drops the tenant filter with the soft-delete one, so a tenant-owned table asks for its tenant again
            var tenant = TableShapes.For(table, project).Tenant;
            string tenantWhere = tenant is null ? "" : $".Where(x => x.{tenant.Column.CSharpName()} == context.CurrentTenantId)";
            string tenantAnd = tenant is null ? "" : $" && x.{tenant.Column.CSharpName()} == context.CurrentTenantId";
            o.Append(Fill(Soft, Pairs("§TENANTWHERE", tenantWhere, "§TENANTAND", tenantAnd, "§FLAG", flag, "§SETON", setOn, "§SETBY", setBy, "§CLEARON", clearOn, "§CLEARBY", clearBy, "§ORDER", order, "§BYLINE", byLine, "§NOWLINE", soft.DeletedOn is null ? "" : "        var now = DateTime.Now;\n", "§W_NOTDELETED", RowShapeWords.NotDeleted)));
            delete.Append("        return await SoftDeleteAsync(context, id, caller);\n");
            maps.Append(Fill("        app.MapGet(\"§R/deleted\", DeletedAsync)§ADMIN;\n        app.MapPost(\"§R/{id}/restore\", RestoreAsync)§ADMIN;\n"));
        }

        var content = TableShapes.For(table, project).Content;
        if (content is not null)
        {
            string published = content.PublishedOn?.CSharpName() ?? "";
            string storedSelect = content.PublishedOn is null ? "" : $", x.{published}";
            string restorePublished = content.PublishedOn is null ? "" : $"        row.{published} = isNew ? null : stored!.{published};\n";
            string stampPublished = content.PublishedOn is null ? "" : $"\n                    .SetProperty(x => x.{published}, x => x.{published} ?? now)";
            string nowLine = content.PublishedOn is null ? "" : $"        var now = {content.PublishedOn.CSharpBase()}.Now;\n";
            string order = content.PublishedOn is null ? ".OrderByDescending(x => x." + key.CSharpName() + ")" : $".OrderByDescending(x => x.{published}).ThenByDescending(x => x.{key.CSharpName()})";
            string anonymous = project.ApiAuth ? ".AllowAnonymous()" : "";
            string publicSelect = content.PublicColumns is null ? "" : $".Select(x => new {{ {string.Join(", ", content.PublicColumns.Select(c => "x." + c.CSharpName()))} }})";
            // the public routes have no caller, so the tenant is the one the request host names; IgnoreQueryFilters drops the soft-delete filter with the tenant one
            string httpParam = "", publicSource = $"context.Set<{table.TableName}>().AsNoTracking()", tenantList = "", tenantSlug = "", httpArg = "";
            if (content.TenantColumn is { } tenantColumn)
            {
                string softAnd = TableShapes.For(table, project).SoftDelete is { } softFlag ? $" && !x.{softFlag.Flag.CSharpName()}" : "";
                httpParam = ", HttpContext http";
                httpArg = ", http";
                publicSource = $"context.Set<{table.TableName}>().IgnoreQueryFilters().AsNoTracking().Where(x => x.{tenantColumn.CSharpName()} == tenant{softAnd})";
                tenantList = "        if (await TenantHost.FindAsync(context, http, http.RequestAborted) is not int tenant)\n            return Results.Ok(Array.Empty<object>());\n";
                tenantSlug = "        if (await TenantHost.FindAsync(context, http, http.RequestAborted) is not int tenant)\n            return Results.NotFound();\n";
            }
            o.Append(ContentRulesWriter.Members(content, contextType));
            o.Append(Fill(Content, Pairs("§HTTPPARAM", httpParam, "§PUBLICSOURCE", publicSource, "§TENANTLIST", tenantList, "§TENANTSLUG", tenantSlug,"§TITLE", content.Title.CSharpName(), "§SLUG", content.Slug.CSharpName(), "§STATUS", content.Status.CSharpName(), "§SLUGMAX", content.SlugLength.ToString(),
                "§PUBLICSELECT", publicSelect, "§STOREDSELECT", storedSelect, "§RESTOREPUBLISHED", restorePublished, "§STAMPPUBLISHED", stampPublished, "§NOWLINE", nowLine, "§ORDER", order,
                "§DRAFT", ContentWords.Draft, "§PUBLISHED", ContentWords.Published, "§ARCHIVED", ContentWords.Archived, "§FALLBACK", ContentWords.FallbackSlug, "§W_TAKEN", ContentWords.SlugTaken)));
            save.Append("        if (await CheckContentAsync(context, row, isNew) is { } contentProblem)\n            return contentProblem;\n");
            string publishRoute = "        app.MapPost(\"§R/{id}/publish\", (§CTX context, §KT id) => SetStatusAsync(context, id, \"" + ContentWords.Published + "\"))§AUTH;\n";
            string unpublishRoute = "        app.MapPost(\"§R/{id}/unpublish\", (§CTX context, §KT id) => SetStatusAsync(context, id, \"" + ContentWords.Draft + "\"))§AUTH;\n";
            string archiveRoute = "        app.MapPost(\"§R/{id}/archive\", (§CTX context, §KT id) => SetStatusAsync(context, id, \"" + ContentWords.Archived + "\"))§AUTH;\n";
            if (content.NeedsApproval)
            {
                // publishing asks for a second person's approval (RowApprovals); leaving the pending state ends the request
                publishRoute = "        app.MapPost(\"§R/{id}/publish\", (§CTX context, System.Security.Claims.ClaimsPrincipal caller, §KT id) => PublishAsync(context, caller, id))§AUTH;\n";
                unpublishRoute = "        app.MapPost(\"§R/{id}/unpublish\", (§CTX context, System.Security.Claims.ClaimsPrincipal caller, §KT id) => LeaveAsync(context, caller, id, \"" + ContentWords.Draft + "\"))§AUTH;\n";
                archiveRoute = "        app.MapPost(\"§R/{id}/archive\", (§CTX context, System.Security.Claims.ClaimsPrincipal caller, §KT id) => LeaveAsync(context, caller, id, \"" + ContentWords.Archived + "\"))§AUTH;\n";
                o.Append(Fill(Approval, ("§STATUS", content.Status.CSharpName()), ("§PUBLISHED", ContentWords.Published)));
            }
            maps.Append(Fill(publishRoute + unpublishRoute + archiveRoute
                + "        app.MapGet(\"§R/public\", (§CTX context" + httpParam + ", int? pageNumber, int? pageSize) => PublicListAsync(context" + httpArg + ", pageNumber, pageSize))" + anonymous + ";\n"
                + "        app.MapGet(\"§R/public/{slug}\", (§CTX context" + httpParam + ", string slug) => PublicBySlugAsync(context" + httpArg + ", slug))" + anonymous + ";\n"));
        }

        var asset = TableShapes.For(table, project).Asset;
        if (asset is not null)
        {
            int Room(ColumnModel c) => c.CharacterLength > 0 ? c.CharacterLength : int.MaxValue;
            string insertSql = AssetInsertSql(table, asset, dialect);
            string urlSet = asset.Url is null ? "" : $"            await context.Set<§T>().Where(x => x.§K == id).ExecuteUpdateAsync(s => s.SetProperty(x => x.{asset.Url.CSharpName()}, AssetKeys.Cut($\"§R/{{id}}/download\", {Room(asset.Url)})), http.RequestAborted);\n";
            o.Append(Fill(Asset, Pairs("§STORAGEKEY", asset.StorageKey.CSharpName(), "§FILENAME", asset.FileName.CSharpName(), "§MIMECOL", asset.MimeType.CSharpName(), "§SIZECOL", asset.Size.CSharpName(),
                "§SIZETYPE", asset.Size.CSharpBase(), "§NAMEMAX", Room(asset.FileName).ToString(), "§MIMEMAX", Room(asset.MimeType).ToString(), "§URLSET", urlSet, "§INSERTSQL", ApiSampleValues.Json(insertSql))));
            save.Append("        if (await CheckAssetSaveAsync(context, row, isNew) is { } assetProblem)\n            return assetProblem;\n");
            delete.Append("        await RememberFileAsync(context, id);\n");
            maps.Append(Fill("        AssetStores.Use(app.Services);\n        app.MapPost(\"§R/upload\", (§CTX context, HttpContext http) => UploadAsync(context, http))§AUTH;\n        app.MapGet(\"§R/{id}/download\", (§CTX context, HttpContext http, §KT id) => DownloadAsync(context, http, id))§AUTH;\n"));
        }

        if (effective is not null)
        {
            string from = effective.From.CSharpName(), to = effective.To.CSharpName(), dateType = effective.From.CSharpBase();
            bool openEnd = effective.To.IsNullable;
            string today = dateType == "DateOnly" ? "DateOnly.FromDateTime(DateTime.Now)" : "DateTime.Today";
            var groupLines = new StringBuilder();
            var currentLines = new StringBuilder();
            var parameters = new StringBuilder();
            var arguments = new StringBuilder();
            var signature = new StringBuilder();
            int i = 0;
            foreach (var g in effective.Groups)
            {
                string name = g.CSharpName(), type = g.CSharpBase() + "?";
                groupLines.Append($"        var group{i} = row.{name};\n        others = others.Where(x => x.{name} == group{i});\n");
                currentLines.Append($"        if (group{i} is {{ }} g{i})\n            rows = rows.Where(x => x.{name} == g{i});\n");
                parameters.Append($", [FromQuery(Name = \"{JsonNames.Camel(g.Name)}\")] {type} group{i}");
                signature.Append($", {type} group{i}");
                arguments.Append($", group{i}");
                i++;
            }
            string rangeTest = openEnd ? "to is { } end && end < from" : "to < from";
            string overlapTest = openEnd ? "(to == null || x." + from + " <= to) && (x." + to + " == null || x." + to + " >= from)" : "x." + from + " <= to && x." + to + " >= from";
            string currentTest = openEnd ? $"x.{from} <= day && (x.{to} == null || x.{to} >= day)" : $"x.{from} <= day && x.{to} >= day";
            o.Append(Fill(Effective, Pairs("§FROM", from, "§TO", to, "§DATE", dateType, "§TODAY", today, "§RANGETEST", rangeTest, "§OVERLAPTEST", overlapTest, "§CURRENTTEST", currentTest,
                "§GROUPLINES", groupLines.ToString(), "§CURRENTLINES", currentLines.ToString(), "§SIGNATURE", signature.ToString(), "§ARGUMENTS", arguments.ToString(), "§PARAMETERS", parameters.ToString(),
                "§W_RANGE", RowShapeWords.BackwardsRange, "§W_OVERLAP", RowShapeWords.Overlap)));
            save.Append("        if (await CheckEffectiveAsync(context, row) is { } effectiveProblem)\n            return effectiveProblem;\n");
            maps.Append(Fill("        app.MapGet(\"§R/current\", ([FromServices] §CTX context, [FromQuery(Name = \"on\")] §DATE? day" + parameters + ") => CurrentAsync(context, day" + arguments + "))§AUTH;\n", ("§DATE", dateType)));
        }

        if (TableShapes.For(table, project).DefaultRow is { } defaults)
        {
            string flag = defaults.Flag.CSharpName();
            var groupLines = new StringBuilder();
            int g = 0;
            foreach (var group in defaults.Groups)
            {
                string name = group.CSharpName();
                groupLines.Append($"        var group{g} = row.{name};\n        others = others.Where(x => x.{name} == group{g});\n");
                g++;
            }
            o.Append(Fill(DefaultRow, Pairs("§FLAG", flag, "§GROUPLINES", groupLines.ToString())));
            save.Append("        if (await CheckDefaultAsync(context, row) is { } defaultProblem)\n            return defaultProblem;\n");
            delete.Insert(0, "        if (await CheckDefaultDeleteAsync(context, id) is { } defaultDeleteProblem)\n            return defaultDeleteProblem;\n");
            maps.Append(Fill("        app.MapPost(\"§R/{id}/make-default\", (§CTX context, §KT id) => MakeDefaultAsync(context, id))§AUTH;\n"));
        }

        if (SnapshotPlan.For(table, project, database) is { } snapshot)
        {
            var newLines = new StringBuilder();
            var storedLines = new StringBuilder();
            int p = 0;
            foreach (var parent in snapshot.Copies.GroupBy(c => c.Link.Name, StringComparer.OrdinalIgnoreCase))
            {
                var first = parent.First();
                string linkName = first.Link.CSharpName(), parentTable = first.Parent.TableName, parentKey = first.ParentKey.CSharpName();
                string select = string.Join(", ", parent.Select(c => $"{c.Source.CSharpName()} = x.{c.Source.CSharpName()}"));
                string assigns = string.Concat(parent.Select(c => $"                row.{c.Target.CSharpName()} = parent{p}.{c.Source.CSharpName()};\n"));
                string guardStart = first.Link.IsNullable ? $"            if (row.{linkName} is {{ }} link{p})\n            {{\n" : "            {\n";
                string equals = first.Link.IsNullable ? $"link{p}" : $"row.{linkName}";
                newLines.Append($"{guardStart}                var parent{p} = await context.Set<{parentTable}>().Where(x => x.{parentKey} == {equals}).Select(x => new {{ {select} }}).FirstOrDefaultAsync();\n                if (parent{p} is null)\n                    return RowShapeProblems.SnapshotParent(\"{RowShapeWords.SnapshotParentMissing(parentTable)}\");\n{assigns}            }}\n");
                p++;
            }
            string storedSelect = string.Join(", ", snapshot.Copies.Select(c => $"{c.Target.CSharpName()} = x.{c.Target.CSharpName()}"));
            foreach (var c in snapshot.Copies)
                storedLines.Append($"                row.{c.Target.CSharpName()} = stored.{c.Target.CSharpName()};\n");
            string totalLine = snapshot.Total is null ? "" : $"        row.{snapshot.Total.Target.CSharpName()} = ({snapshot.Total.Target.CSharpBase()})(row.{snapshot.Total.FactorA.CSharpName()} * row.{snapshot.Total.FactorB.CSharpName()});\n";
            o.Append(Fill(SnapshotCheck, Pairs("§NEWLINES", newLines.ToString(), "§STOREDSELECT", storedSelect, "§STOREDLINES", storedLines.ToString(), "§TOTALLINE", totalLine)));
            save.Append("        if (await CheckSnapshotAsync(context, row, isNew) is { } snapshotProblem)\n            return snapshotProblem;\n");
        }

        if (PolymorphicPlan.LinkOf(table, project, database) is { } link)
        {
            var cases = new StringBuilder();
            foreach (var target in link.Targets)
                cases.Append($"            case \"{target.Table.TableName.ToLowerInvariant()}\":\n                row.{link.TypeColumn.CSharpName()} = \"{target.Table.TableName}\";\n                found = await context.Set<{target.Table.TableName}>().AnyAsync(x => x.{target.Key.CSharpName()} == row.{link.IdColumn.CSharpName()});\n                break;\n");
            o.Append(Fill(LinkCheck, Pairs("§TYPE", link.TypeColumn.CSharpName(), "§CASES", cases.ToString(), "§TYPELIST", ApiSampleValues.Json(LinkWords.UnknownType(link.Targets.Select(t => t.Table.TableName))))));
            save.Append("        if (await CheckLinkAsync(context, row) is { } linkProblem)\n            return linkProblem;\n");
        }

        if (PolymorphicPlan.TargetOf(table, project, database) is { } linked)
        {
            var uses = new StringBuilder();
            var removals = new StringBuilder();
            foreach (var use in linked.Links)
            {
                string where = $"x => x.{use.TypeColumn.CSharpName()} == \"{table.TableName}\" && x.{use.IdColumn.CSharpName()} == id";
                if (use.RemoveWithTarget)
                    removals.Append($"        await context.Set<{use.Table.TableName}>().Where({where}).ExecuteDeleteAsync();\n");
                else
                    uses.Append($"        if (await context.Set<{use.Table.TableName}>().AnyAsync({where}))\n            return LinkProblems.InUse(\"{use.Table.TableName}\");\n");
            }
            if (uses.Length > 0)
            {
                o.Append(Fill("    /// <summary> A row that links still name is not deleted (409). </summary>\n    public static async Task<IResult?> CheckLinksAsync(§CTX context, §KT id)\n    {\n") + uses + "        return null;\n    }\n\n");
                delete.Insert(0, "        if (await CheckLinksAsync(context, id) is { } linkedProblem)\n            return linkedProblem;\n");
            }
            if (removals.Length > 0 && TableShapes.For(table, project).Asset is null)
                o.Append(Fill("    /// <summary> Once the row is gone, the links that named it are removed. </summary>\n    public static async Task AfterDeleteAsync(§CTX context, §KT id)\n    {\n") + removals + "    }\n\n");
        }

        if (save.Length > 0)
            o.Append(Fill("    /// <summary> Runs before a create or update saves <paramref name=\"row\"/>; a result refuses the save. </summary>\n    public static async Task<IResult?> CheckSaveAsync(§CTX context, §T row, bool isNew)\n    {\n") + save + "        return null;\n    }\n\n");
        if (delete.Length > 0)
        {
            bool endsInReturn = delete.ToString().Contains("return await SoftDeleteAsync");
            o.Append(Fill("    /// <summary> Runs before a delete; a result answers the request instead (a refusal, or the soft delete itself). </summary>\n    public static async Task<IResult?> CheckDeleteAsync(§CTX context, §KT id, System.Security.Claims.ClaimsPrincipal? caller)\n    {\n") + delete + (endsInReturn ? "" : "        return null;\n") + "    }\n\n");
        }
        o.Append("    public static void Map(WebApplication app)\n    {\n" + maps + "    }\n}\n\n");
        return o.ToString();
    }

    private static (string, string)[] Pairs(params string[] values)
    {
        var pairs = new (string, string)[values.Length / 2];
        for (int i = 0; i < pairs.Length; i++)
            pairs[i] = (values[i * 2], values[i * 2 + 1]);
        return pairs;
    }

    private const string Shared = """
public static class RowShapeProblems
{
    public static IResult Problem(int status, string type, string title, string detail) => Results.Problem(statusCode: status, type: type, title: title, detail: detail);

    public static IResult Cycle(string detail) => Problem(400, "§TREE_CYCLE", "Not a valid parent", detail);
    public static IResult TooDeep(string detail) => Problem(400, "§TREE_DEEP", "Too deep", detail);
    public static IResult HasChildren(string detail) => Problem(409, "§TREE_CHILDREN", "Has child rows", detail);
    public static IResult BadRange(string detail) => Problem(400, "§EFF_RANGE", "Not a valid period", detail);
    public static IResult Overlap(string detail) => Problem(409, "§EFF_OVERLAP", "Overlapping period", detail);
    public static IResult NotDeleted(string detail) => Problem(409, "§NOT_DELETED", "Not deleted", detail);
    public static IResult SnapshotParent(string detail) => Problem(400, "§SNAP_PARENT", "§SNAP_TITLE", detail);
    public static IResult SlugTaken(string detail) => Problem(409, "§SLUG_TAKEN", "Slug taken", detail);
}

/// <summary> One row of a tree answer, depth first: level 1 is a root. </summary>
public sealed record TreeNode(long Id, long? ParentId, int Depth, bool HasChildren, string Text);

""";

    private const string LinkShared = """
public static class LinkProblems
{

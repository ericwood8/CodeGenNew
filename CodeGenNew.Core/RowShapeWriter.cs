    {
§NOWLINE§BYLINE        int changed = await context.Set<§T>().Where(x => x.§K == id)
            .ExecuteUpdateAsync(s => s
                .SetProperty(x => x.§FLAG, true)§SETON§SETBY);
        return changed == 0 ? Results.NotFound() : Results.Ok();
    }

    /// <summary> The rows that were soft deleted, the last deleted first. </summary>

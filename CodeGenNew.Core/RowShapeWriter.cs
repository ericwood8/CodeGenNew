using System.Text;

namespace CodeGenNew.Core;

/// <summary> The C# of the row-shape checks and routes (<c>TreeTables</c>, <c>SoftDeleteTables</c>, <c>EffectiveDatedTables</c>): per table a static <c>&lt;Table&gt;Shape</c> class the table's API calls before a save and before a delete
/// (<c>CheckSaveAsync</c>, <c>CheckDeleteAsync</c>) and that maps the extra routes. The text uses <c>§</c> tokens so the code reads as code. </summary>
public static class RowShapeWriter
{
    /// <summary> Whether the table's API has to call <c>CheckSaveAsync</c>. </summary>
    public static bool HasSaveCheck(TableModel table, ProjectSettings project) => TreePlan.For(table, project) is not null || EffectiveDatePlan.For(table, project) is not null;

    /// <summary> Whether the table's API has to call <c>CheckDeleteAsync</c>. </summary>
    public static bool HasDeleteCheck(TableModel table, ProjectSettings project) => TreePlan.For(table, project) is not null || SoftDeletePlan.For(table, project) is not null;

    public static string File(DatabaseModel database, ProjectSettings project, string contextType, string[] usings)
    {
        var tables = database.Tables.Where(t => RowShapePlan.Has(t, project)).OrderBy(t => t.TableName, StringComparer.OrdinalIgnoreCase).ToList();
        var o = new StringBuilder();
        foreach (string u in usings)
            o.Append($"using {u};\n");
        o.Append("using Microsoft.AspNetCore.Mvc;\nusing Microsoft.EntityFrameworkCore;\n\n");
        o.Append(Shared.Replace("§TREE_CYCLE", RowShapeWords.TreeCycleType).Replace("§TREE_DEEP", RowShapeWords.TreeTooDeepType).Replace("§TREE_CHILDREN", RowShapeWords.TreeHasChildrenType)
            .Replace("§EFF_RANGE", RowShapeWords.EffectiveRangeType).Replace("§EFF_OVERLAP", RowShapeWords.EffectiveOverlapType).Replace("§NOT_DELETED", RowShapeWords.NotDeletedType));
        foreach (var table in tables)
            o.Append(PerTable(table, project, contextType));
        o.Append("/// <summary> Maps the extra routes of every table named in TreeTables, SoftDeleteTables or EffectiveDatedTables. Generated by API_RowShapes. </summary>\npublic static class RowShapeApi\n{\n    public static void Register(WebApplication app)\n    {\n");
        foreach (var table in tables)
            o.Append($"        {table.TableName}Shape.Map(app);\n");
        o.Append("    }\n}\n");
        return o.ToString();
    }

    private static string PerTable(TableModel table, ProjectSettings project, string contextType)
    {
        var tree = TreePlan.For(table, project);
        var soft = SoftDeletePlan.For(table, project);
        var effective = EffectiveDatePlan.For(table, project);
        var key = table.PrimaryKeyColumns[0];
        string keyType = key.CSharpBase();
        string route = ApiRequests.Route(table);
        string auth = project.ApiAuth ? ".RequireAuthorization()" : "";
        string admin = project.ApiAuth ? ".RequireAuthorization().RequireWriteRoles([AuthNames.AdminRole])" : "";
        var o = new StringBuilder();
        var maps = new StringBuilder();
        var save = new StringBuilder();
        var delete = new StringBuilder();

        string Fill(string text, params (string Token, string Value)[] extra)
        {
            var values = new List<(string Token, string Value)>
            {
                ("§CTX", contextType), ("§T", table.TableName), ("§KT", keyType), ("§K", key.CSharpName()), ("§R", route), ("§AUTH", auth), ("§ADMIN", admin)
            };
            values.AddRange(extra);
            foreach (var (token, value) in values.OrderByDescending(v => v.Token.Length))
                text = text.Replace(token, value);
            return text;
        }

        o.Append(Fill("/// <summary> The row-shape checks and routes of §T (" + string.Join(", ", new[] { tree is null ? null : "TreeTables", soft is null ? null : "SoftDeleteTables", effective is null ? null : "EffectiveDatedTables" }.OfType<string>())
            + "): the table's API calls CheckSaveAsync before it saves a row and CheckDeleteAsync before it deletes one. Generated by API_RowShapes. </summary>\npublic static class §TShape\n{\n"));

        if (tree is not null)
        {
            string parent = tree.Parent.CSharpName(), parentType = tree.Parent.CSharpBase();
            string text = tree.Text is null ? "" : tree.Text.CSharpName();
            string textValue = tree.Text is null ? "r.Id.ToString()" : tree.Text.IsNullable ? "r.Text ?? \"\"" : "r.Text";
            string textSelect = tree.Text is null ? "" : $", Text = x.{text}";
            string[] values = ["§P", parent, "§PT", parentType, "§MAX", tree.MaxDepth.ToString(), "§TEXTSELECT", textSelect, "§TEXTVALUE", textValue,
                "§W_OWN", RowShapeWords.OwnParent, "§W_UNDER", RowShapeWords.UnderItself, "§W_CHILDREN", RowShapeWords.HasChildren, "§W_DEEP", RowShapeWords.TooDeep(tree.MaxDepth)];
            o.Append(Fill(Tree, Pairs(values)));
            save.Append("        if (await CheckTreeAsync(context, row) is { } treeProblem)\n            return treeProblem;\n");
            delete.Append("        if (await CheckChildrenAsync(context, id) is { } childrenProblem)\n            return childrenProblem;\n");
            maps.Append(Fill("        app.MapGet(\"§R/tree\", TreeAsync)§AUTH;\n        app.MapPost(\"§R/{id}/promote-children\", PromoteChildrenAsync)§AUTH;\n"));
        }

        if (soft is not null)
        {
            string flag = soft.Flag.CSharpName();
            string setOn = soft.DeletedOn is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedOn.CSharpName()}, now)";
            string setBy = soft.DeletedBy is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedBy.CSharpName()}, by)";
            string clearOn = soft.DeletedOn is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedOn.CSharpName()}, ({soft.DeletedOn.CSharpBase()}?)null)";
            string clearBy = soft.DeletedBy is null ? "" : $"\n                .SetProperty(x => x.{soft.DeletedBy.CSharpName()}, (string?)null)";
            string order = soft.DeletedOn is null ? ".OrderByDescending(x => x." + key.CSharpName() + ")" : $".OrderByDescending(x => x.{soft.DeletedOn.CSharpName()}).ThenByDescending(x => x.{key.CSharpName()})";
            string byLine = soft.DeletedBy is null ? "" : $"        string? by = caller?.Identity?.Name is {{ }} name ? (name.Length <= {(soft.DeletedBy.CharacterLength > 0 ? soft.DeletedBy.CharacterLength : 1000000)} ? name : name[..{(soft.DeletedBy.CharacterLength > 0 ? soft.DeletedBy.CharacterLength : 1000000)}]) : null;\n";
            // IgnoreQueryFilters drops the tenant filter with the soft-delete one, so a tenant-owned table asks for its tenant again
            var tenant = TenantPlan.OwnedBy(table, project);
            string tenantWhere = tenant is null ? "" : $".Where(x => x.{tenant.Column.CSharpName()} == context.CurrentTenantId)";
            string tenantAnd = tenant is null ? "" : $" && x.{tenant.Column.CSharpName()} == context.CurrentTenantId";
            o.Append(Fill(Soft, Pairs("§TENANTWHERE", tenantWhere, "§TENANTAND", tenantAnd, "§FLAG", flag, "§SETON", setOn, "§SETBY", setBy, "§CLEARON", clearOn, "§CLEARBY", clearBy, "§ORDER", order, "§BYLINE", byLine, "§NOWLINE", soft.DeletedOn is null ? "" : "        var now = DateTime.Now;\n", "§W_NOTDELETED", RowShapeWords.NotDeleted)));
            delete.Append("        return await SoftDeleteAsync(context, id, caller);\n");
            maps.Append(Fill("        app.MapGet(\"§R/deleted\", DeletedAsync)§ADMIN;\n        app.MapPost(\"§R/{id}/restore\", RestoreAsync)§ADMIN;\n"));
        }

        if (effective is not null)
        {
            string from = effective.From.CSharpName(), to = effective.To.CSharpName(), dateType = effective.From.CSharpBase();
            bool openEnd = effective.To.IsNullable;
            string today = dateType == "DateOnly" ? "DateOnly.FromDateTime(DateTime.Now)" : "DateTime.Today";
            var groupLines = new StringBuilder();
            var currentLines = new StringBuilder();
            var parameters = new StringBuilder();
            var arguments = new StringBuilder();
            var signature = new StringBuilder();
            int i = 0;
            foreach (var g in effective.Groups)
            {
                string name = g.CSharpName(), type = g.CSharpBase() + "?";
                groupLines.Append($"        var group{i} = row.{name};\n        others = others.Where(x => x.{name} == group{i});\n");
                currentLines.Append($"        if (group{i} is {{ }} g{i})\n            rows = rows.Where(x => x.{name} == g{i});\n");
                parameters.Append($", [FromQuery(Name = \"{JsonNames.Camel(g.Name)}\")] {type} group{i}");
                signature.Append($", {type} group{i}");
                arguments.Append($", group{i}");
                i++;
            }
            string rangeTest = openEnd ? "to is { } end && end < from" : "to < from";
            string overlapTest = openEnd ? "(to == null || x." + from + " <= to) && (x." + to + " == null || x." + to + " >= from)" : "x." + from + " <= to && x." + to + " >= from";
            string currentTest = openEnd ? $"x.{from} <= day && (x.{to} == null || x.{to} >= day)" : $"x.{from} <= day && x.{to} >= day";
            o.Append(Fill(Effective, Pairs("§FROM", from, "§TO", to, "§DATE", dateType, "§TODAY", today, "§RANGETEST", rangeTest, "§OVERLAPTEST", overlapTest, "§CURRENTTEST", currentTest,
                "§GROUPLINES", groupLines.ToString(), "§CURRENTLINES", currentLines.ToString(), "§SIGNATURE", signature.ToString(), "§ARGUMENTS", arguments.ToString(), "§PARAMETERS", parameters.ToString(),
                "§W_RANGE", RowShapeWords.BackwardsRange, "§W_OVERLAP", RowShapeWords.Overlap)));
            save.Append("        if (await CheckEffectiveAsync(context, row) is { } effectiveProblem)\n            return effectiveProblem;\n");
            maps.Append(Fill("        app.MapGet(\"§R/current\", ([FromServices] §CTX context, [FromQuery(Name = \"on\")] §DATE? day" + parameters + ") => CurrentAsync(context, day" + arguments + "))§AUTH;\n", ("§DATE", dateType)));
        }

        if (save.Length > 0)
            o.Append(Fill("    /// <summary> Runs before a create or update saves <paramref name=\"row\"/>; a result refuses the save. </summary>\n    public static async Task<IResult?> CheckSaveAsync(§CTX context, §T row, bool isNew)\n    {\n") + save + "        return null;\n    }\n\n");
        if (delete.Length > 0)
        {
            bool endsInReturn = delete.ToString().Contains("return await SoftDeleteAsync");
            o.Append(Fill("    /// <summary> Runs before a delete; a result answers the request instead (a refusal, or the soft delete itself). </summary>\n    public static async Task<IResult?> CheckDeleteAsync(§CTX context, §KT id, System.Security.Claims.ClaimsPrincipal? caller)\n    {\n") + delete + (endsInReturn ? "" : "        return null;\n") + "    }\n\n");
        }
        o.Append("    public static void Map(WebApplication app)\n    {\n" + maps + "    }\n}\n\n");
        return o.ToString();
    }

    private static (string, string)[] Pairs(params string[] values)
    {
        var pairs = new (string, string)[values.Length / 2];
        for (int i = 0; i < pairs.Length; i++)
            pairs[i] = (values[i * 2], values[i * 2 + 1]);
        return pairs;
    }

    private const string Shared = """
public static class RowShapeProblems
{
    public static IResult Problem(int status, string type, string title, string detail) => Results.Problem(statusCode: status, type: type, title: title, detail: detail);

    public static IResult Cycle(string detail) => Problem(400, "§TREE_CYCLE", "Not a valid parent", detail);
    public static IResult TooDeep(string detail) => Problem(400, "§TREE_DEEP", "Too deep", detail);
    public static IResult HasChildren(string detail) => Problem(409, "§TREE_CHILDREN", "Has child rows", detail);
    public static IResult BadRange(string detail) => Problem(400, "§EFF_RANGE", "Not a valid period", detail);
    public static IResult Overlap(string detail) => Problem(409, "§EFF_OVERLAP", "Overlapping period", detail);
    public static IResult NotDeleted(string detail) => Problem(409, "§NOT_DELETED", "Not deleted", detail);
}

/// <summary> One row of a tree answer, depth first: level 1 is a root. </summary>
public sealed record TreeNode(long Id, long? ParentId, int Depth, bool HasChildren, string Text);

""";

    private const string Tree = """
    public const int MaxDepth = §MAX;

    /// <summary> A parent that is the row itself or one of its descendants would make a cycle, and a level past MaxDepth (0: no limit) is too deep. </summary>
    public static async Task<IResult?> CheckTreeAsync(§CTX context, §T row)
    {
        if (row.§P is not { } start)
            return null;
        if (start == row.§K)
            return RowShapeProblems.Cycle("§W_OWN");
        var set = context.Set<§T>().AsNoTracking();
        int depth = 1;
        var seen = new HashSet<§KT> { row.§K };
        §PT? up = start;
        while (up is { } id)
        {
            if (!seen.Add(id))
                return RowShapeProblems.Cycle("§W_UNDER");
            depth++;
            up = await set.Where(x => x.§K == id).Select(x => x.§P).FirstOrDefaultAsync();
        }
        if (MaxDepth > 0)
        {
            int below = 0;
            var level = new List<§KT> { row.§K };
            while (depth + below <= MaxDepth)
            {
                var ids = level;
                level = await set.Where(x => x.§P != null && ids.Contains(x.§P.Value)).Select(x => x.§K).ToListAsync();
                if (level.Count == 0)
                    break;
                below++;
            }
            if (depth + below > MaxDepth)
                return RowShapeProblems.TooDeep("§W_DEEP");
        }
        return null;
    }

    /// <summary> A row with children is not deleted: they would be orphaned or refused by the foreign key. </summary>
    public static async Task<IResult?> CheckChildrenAsync(§CTX context, §KT id) =>
        await context.Set<§T>().AsNoTracking().AnyAsync(x => x.§P == id) ? RowShapeProblems.HasChildren("§W_CHILDREN") : null;

    /// <summary> The children of the row become children of the row's own parent (roots when it is a root); the row stays. </summary>
    public static async Task<IResult> PromoteChildrenAsync(§CTX context, §KT id)
    {
        var found = await context.Set<§T>().AsNoTracking().Where(x => x.§K == id).Select(x => new { x.§P }).ToListAsync();
        if (found.Count == 0)
            return Results.NotFound();
        var parent = found[0].§P;
        int moved = await context.Set<§T>().Where(x => x.§P == id).ExecuteUpdateAsync(s => s.SetProperty(x => x.§P, parent));
        return Results.Ok(new { moved });
    }

    /// <summary> Every row depth first (children after their parent, by name), with its level. Only a row with no parent is a root: a row whose parent is hidden (soft deleted) is left out with the rest of that branch. </summary>
    public static async Task<IResult> TreeAsync(§CTX context)
    {
        var rows = await context.Set<§T>().AsNoTracking().Select(x => new { Id = x.§K, Parent = x.§P§TEXTSELECT }).ToListAsync();
        var known = rows.Select(r => (long)r.Id).ToHashSet();
        var byParent = rows.Where(r => r.Parent is { } p && known.Contains(p)).ToLookup(r => (long)r.Parent!.Value);
        var result = new List<TreeNode>(rows.Count);
        var visited = new HashSet<long>();
        void Walk(long id, long? parent, int depth, string text)
        {
            if (!visited.Add(id))
                return;
            var children = byParent[id].OrderBy(r => §TEXTVALUE, StringComparer.OrdinalIgnoreCase).ThenBy(r => r.Id).ToList();
            result.Add(new TreeNode(id, parent, depth, children.Count > 0, text));
            foreach (var r in children)
                Walk(r.Id, id, depth + 1, §TEXTVALUE);
        }
        foreach (var r in rows.Where(r => r.Parent is null).OrderBy(r => §TEXTVALUE, StringComparer.OrdinalIgnoreCase).ThenBy(r => r.Id))
            Walk(r.Id, null, 1, §TEXTVALUE);
        return Results.Ok(result);
    }


""";


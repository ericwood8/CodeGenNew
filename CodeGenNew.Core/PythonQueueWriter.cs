namespace CodeGenNew.Core;

/// <summary> The Python (FastAPI) counterpart of <see cref="QueueWriter"/>: <c>app/routes/queue.py</c>, the <c>stats</c>, <c>failed</c>, <c>claim</c>, <c>{id}/renew</c>, <c>{id}/complete</c>, <c>{id}/fail</c> and <c>{id}/retry</c> routes of every table
/// in <c>QueueTables</c>, with the same sentences (<see cref="QueueWords"/>), problem type and status codes. The routes are written once; each table adds one <c>QueueSpec</c> that names its model and the attributes of its
/// columns. Every change of status is one guarded UPDATE of the row in the status it expects. </summary>
public static class PythonQueueWriter
{
    public static string File(IReadOnlyList<QueueTable> tables, ProjectSettings project)
    {
        var imports = new SortedSet<string>(StringComparer.Ordinal);
        var specs = new System.Text.StringBuilder();
        foreach (var q in tables)
        {
            var main = PythonTable.Of(q.Table, project);
            string Attr(ColumnModel c) => main.FieldOf(c).Name;
            imports.Add($"from app.models.{main.Module} import {main.Class}");
            imports.Add($"from app.schemas.{main.Module} import {main.Schema}");
            string by = q.ClaimedBy is null ? "None" : $"\"{Attr(q.ClaimedBy)}\"";
            string error = q.LastError is null ? "None" : $"\"{Attr(q.LastError)}\"";
            specs.Append($"    QueueSpec(\n        table=\"{q.Table.TableName}\", route=\"{main.Route}\", row={main.Class}, schema={main.Schema},\n" +
                $"        key=\"{Attr(q.Key)}\", status=\"{Attr(q.Status)}\", retry=\"{Attr(q.Retry)}\", created=\"{Attr(q.Created)}\", claimed=\"{Attr(q.Claimed)}\", processed=\"{Attr(q.Processed)}\",\n" +
                $"        claimed_by={by}, by_length={Length(q.ClaimedBy)}, last_error={error}, error_length={Length(q.LastError)},\n    ),\n");
        }
        string text = Template;
        foreach (var (token, value) in new (string, string)[]
        {
            ("§IMPORTS", string.Join("\n", imports)), ("§SPECS", specs.ToString().TrimEnd('\n')),
            ("§AUTHIMPORT\n", project.ApiAuth ? "from app.auth import require_user\n" : ""), ("§DEPS", project.ApiAuth ? ", dependencies=[Depends(require_user)]" : ""),
            ("§T_STATE", QueueWords.WrongStateType), ("§W_NOTCLAIMED", PythonNames.Str(QueueWords.NotClaimed)), ("§W_NOTFAILED", PythonNames.Str(QueueWords.NotFailed)),
            ("§MAX", project.QueueMaxRetries.ToString()), ("§MIN", project.QueueClaimMinutes.ToString()), ("§ATTEMPTS", QueueWords.ClaimAttempts.ToString()), ("§FAILEDROWS", QueueWords.FailedRows.ToString()),
            ("§PENDING", QueueStatus.Pending), ("§CLAIMED", QueueStatus.Claimed), ("§DONE", QueueStatus.Done), ("§FAILED", QueueStatus.Failed),
            ("§CONFLICT", HttpStatus.Conflict.ToString()), ("§NOTFOUND", HttpStatus.NotFound.ToString())
        }.OrderByDescending(v => v.Item1.Length))
            text = text.Replace(token, value);
        return text;
    }

    private static string Length(ColumnModel? column) => column is null ? "0" : (column.CharacterLength > 0 ? column.CharacterLength : 0).ToString();

    private const string Template = """"
"""The work queues (QueueTables): a worker claims the oldest pending row, then completes or fails it; a failed row can be retried. The same routes, sentences and problem type as the ASP.NET API (API_Queue).
Every change of status is one UPDATE of the row in the status it expects, so two workers never get the same row. Generated by PY_Queue."""
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Any

from fastapi import APIRouter, Depends, Response
from pydantic import BaseModel
from sqlalchemy import case, func, select, update
from sqlalchemy.orm import Session

§AUTHIMPORT
from app.db import get_session
§IMPORTS
from app.support import ApiError

PROBLEM_WRONG_STATE = "§T_STATE"
NOT_CLAIMED = §W_NOTCLAIMED
NOT_FAILED = §W_NOTFAILED

PENDING, CLAIMED, DONE, FAILED = "§PENDING", "§CLAIMED", "§DONE", "§FAILED"
MAX_RETRIES = §MAX
CLAIM_TIMEOUT = timedelta(minutes=§MIN)
CLAIM_ATTEMPTS = §ATTEMPTS
FAILED_ROWS = §FAILEDROWS


class QueueFailure(BaseModel):
    """What a worker sends when it fails a row."""

    error: str | None = None


class QueueCounts(BaseModel):
    """The rows in each status and the oldest pending row."""

    pending: int
    claimed: int
    done: int
    failed: int
    oldestPendingId: int | None = None
    oldestPendingOn: datetime | None = None


@dataclass(frozen=True)
class QueueSpec:
    """One table of QueueTables: its model and schema and the attribute names of its columns (claimed_by and last_error are optional; a length of 0 means no limit)."""

    table: str
    route: str
    row: Any
    schema: Any
    key: str
    status: str
    retry: str
    created: str
    claimed: str
    processed: str
    claimed_by: str | None
    by_length: int
    last_error: str | None
    error_length: int

    def col(self, name: str) -> Any:
        return getattr(self.row, getattr(self, name))


SPECS = [
§SPECS
]


def fit(text: str | None, length: int) -> str | None:
    return text if text is None or length == 0 or len(text) <= length else text[:length]


def wrong_state(detail: str) -> ApiError:
    return ApiError(§CONFLICT, "Wrong state", problem_type=PROBLEM_WRONG_STATE, detail=detail)


def release_stale(session: Session, spec: QueueSpec) -> None:
    """A claim nobody completed within CLAIM_TIMEOUT goes back to pending."""
    values: dict[str, Any] = {spec.status: PENDING, spec.claimed: None}
    if spec.claimed_by:
        values[spec.claimed_by] = None
    session.execute(update(spec.row).where(spec.col("status") == CLAIMED, spec.col("claimed") < datetime.now() - CLAIM_TIMEOUT).values(values))
    session.commit()


def answer(session: Session, spec: QueueSpec, key: int, changed: int, detail: str) -> Any:
    session.expire_all()
    row = session.get(spec.row, key)
    if row is None:
        raise ApiError(§NOTFOUND, "Not found.")
    if changed != 1:
        raise wrong_state(detail)
    return row


def stats(session: Session, spec: QueueSpec) -> QueueCounts:
    release_stale(session, spec)
    by_status = dict(session.execute(select(spec.col("status"), func.count()).group_by(spec.col("status"))).all())
    oldest = session.execute(select(spec.col("key"), spec.col("created")).where(spec.col("status") == PENDING).order_by(spec.col("created"), spec.col("key")).limit(1)).first()
    return QueueCounts(pending=by_status.get(PENDING, 0), claimed=by_status.get(CLAIMED, 0), done=by_status.get(DONE, 0), failed=by_status.get(FAILED, 0),
                       oldestPendingId=oldest[0] if oldest else None, oldestPendingOn=oldest[1] if oldest else None)


def failed(session: Session, spec: QueueSpec) -> list[Any]:
    return list(session.scalars(select(spec.row).where(spec.col("status") == FAILED).order_by(spec.col("processed").desc(), spec.col("key").desc()).limit(FAILED_ROWS)).all())


def claim(session: Session, spec: QueueSpec, worker: str | None) -> Any | None:
    """The oldest pending row, taken with one UPDATE that still tests that it is pending; None when there is none."""
    release_stale(session, spec)
    for _ in range(CLAIM_ATTEMPTS):
        key = session.scalars(select(spec.col("key")).where(spec.col("status") == PENDING).order_by(spec.col("created"), spec.col("key")).limit(1)).first()
        if key is None:
            return None
        values: dict[str, Any] = {spec.status: CLAIMED, spec.claimed: datetime.now()}
        if spec.claimed_by:
            values[spec.claimed_by] = fit(worker, spec.by_length)
        changed = session.execute(update(spec.row).where(spec.col("key") == key, spec.col("status") == PENDING).values(values)).rowcount
        session.commit()
        if changed == 1:
            session.expire_all()
            return session.get(spec.row, key)
    return None


def renew(session: Session, spec: QueueSpec, key: int) -> Any:
    """The worker that holds a claim says it is still working: the claim starts again, so it is not released after CLAIM_TIMEOUT."""
    changed = session.execute(update(spec.row).where(spec.col("key") == key, spec.col("status") == CLAIMED).values({spec.claimed: datetime.now()})).rowcount
    session.commit()
    return answer(session, spec, key, changed, NOT_CLAIMED)


def complete(session: Session, spec: QueueSpec, key: int) -> Any:
    changed = session.execute(update(spec.row).where(spec.col("key") == key, spec.col("status") == CLAIMED).values({spec.status: DONE, spec.processed: datetime.now()})).rowcount
    session.commit()
    return answer(session, spec, key, changed, NOT_CLAIMED)


def fail(session: Session, spec: QueueSpec, key: int, body: QueueFailure | None) -> Any:
    retry = spec.col("retry")
    exhausted = retry + 1 >= MAX_RETRIES
    # in this order: MySQL reads a column that an earlier assignment of the same UPDATE already changed, so the retry count is written last
    values = [
        (spec.col("status"), case((exhausted, FAILED), else_=PENDING)),
        (spec.col("processed"), case((exhausted, datetime.now()), else_=None)),
        (spec.col("claimed"), None),
    ]
    if spec.claimed_by:
        values.append((getattr(spec.row, spec.claimed_by), None))
    if spec.last_error:
        values.append((getattr(spec.row, spec.last_error), fit(body.error if body else None, spec.error_length)))
    values.append((retry, retry + 1))
    changed = session.execute(update(spec.row).where(spec.col("key") == key, spec.col("status") == CLAIMED).ordered_values(*values)).rowcount
    session.commit()
    return answer(session, spec, key, changed, NOT_CLAIMED)


def retry_row(session: Session, spec: QueueSpec, key: int) -> Any:
    values: dict[str, Any] = {spec.status: PENDING, spec.retry: 0, spec.processed: None, spec.claimed: None}
    if spec.claimed_by:
        values[spec.claimed_by] = None
    changed = session.execute(update(spec.row).where(spec.col("key") == key, spec.col("status") == FAILED).values(values)).rowcount
    session.commit()
    return answer(session, spec, key, changed, NOT_FAILED)


router = APIRouter()


def add_routes(spec: QueueSpec) -> None:
    """The routes of one table. The fixed paths are registered before the paths with an id, and PY_Mod lists this router before the tables' routers (their /{id} would read stats as a key)."""

    @router.get(spec.route + "/stats", response_model=QueueCounts, name=spec.table + "Stats"§DEPS)
    def stats_route(session: Session = Depends(get_session)):
        return stats(session, spec)

    @router.get(spec.route + "/failed", response_model=list[spec.schema], name=spec.table + "Failed"§DEPS)
    def failed_route(session: Session = Depends(get_session)):
        return failed(session, spec)

    @router.post(spec.route + "/claim", response_model=spec.schema, name=spec.table + "Claim"§DEPS)
    def claim_route(worker: str | None = None, session: Session = Depends(get_session)):
        row = claim(session, spec, worker)
        return Response(status_code=204) if row is None else row

    @router.post(spec.route + "/{id}/renew", response_model=spec.schema, name=spec.table + "Renew"§DEPS)
    def renew_route(id: int, session: Session = Depends(get_session)):
        return renew(session, spec, id)

    @router.post(spec.route + "/{id}/complete", response_model=spec.schema, name=spec.table + "Complete"§DEPS)
    def complete_route(id: int, session: Session = Depends(get_session)):
        return complete(session, spec, id)

    @router.post(spec.route + "/{id}/fail", response_model=spec.schema, name=spec.table + "Fail"§DEPS)
    def fail_route(id: int, body: QueueFailure | None = None, session: Session = Depends(get_session)):
        return fail(session, spec, id, body)

    @router.post(spec.route + "/{id}/retry", response_model=spec.schema, name=spec.table + "Retry"§DEPS)
    def retry_route(id: int, session: Session = Depends(get_session)):
        return retry_row(session, spec, id)


for _spec in SPECS:
    add_routes(_spec)
"""";
}

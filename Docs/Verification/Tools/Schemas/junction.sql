CREATE TABLE Region (
    RegionId INTEGER PRIMARY KEY AUTOINCREMENT,
    Name VARCHAR(40) NOT NULL,
    Code VARCHAR(10) NOT NULL,
    Population INTEGER NOT NULL,
    Founded DATETIME NULL,
    Note VARCHAR(50) NULL
);

CREATE TABLE Customer (
    CustomerId INTEGER PRIMARY KEY AUTOINCREMENT,
    RegionId INTEGER NOT NULL REFERENCES Region (RegionId),
    Name VARCHAR(40) NOT NULL,
    Email VARCHAR(80) NOT NULL,
    CreditLimit DECIMAL(10,2) NOT NULL,
    IsActive2 BOOLEAN NOT NULL,
    Note VARCHAR(50) NULL
);

CREATE TABLE Tag (
    TagId INTEGER PRIMARY KEY AUTOINCREMENT,
    Name VARCHAR(40) NOT NULL,
    Colour VARCHAR(20) NOT NULL,
    Priority INTEGER NOT NULL,
    Created DATETIME NOT NULL,
    Note VARCHAR(50) NULL
);

CREATE TABLE CustomerTag (
    CustomerId INTEGER NOT NULL REFERENCES Customer (CustomerId) ON DELETE CASCADE,
    TagId INTEGER NOT NULL REFERENCES Tag (TagId),
    PRIMARY KEY (CustomerId, TagId)
);
